    private const string CmedChavePublicacao = "Cmed.Publicacao";
    private const string CmedChaveImportadoEm = "Cmed.ImportadoEm";
    private const string CmedChaveFontePmc = "Cmed.FontePmc";
    private const string CmedChaveFontePmvg = "Cmed.FontePmvg";
    private const string CmedChaveTotalProdutos = "Cmed.TotalProdutos";
    private const string CmedChaveTotalEans = "Cmed.TotalEans";
    private const string CmedChaveAliquotas = "Cmed.Aliquotas";

    private static void InicializarTabelaCmed(NpgsqlConnection connection)
    {
        connection.Execute("""
            CREATE TABLE IF NOT EXISTS CmedProdutos (
                Id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                Registro      TEXT NOT NULL DEFAULT '',
                Ggrem         TEXT NOT NULL DEFAULT '',
                Ean1          TEXT NULL,
                Ean2          TEXT NULL,
                Ean3          TEXT NULL,
                Substancia    TEXT NOT NULL DEFAULT '',
                Laboratorio   TEXT NOT NULL DEFAULT '',
                Cnpj          TEXT NOT NULL DEFAULT '',
                Produto       TEXT NOT NULL DEFAULT '',
                Apresentacao  TEXT NOT NULL DEFAULT '',
                Classe        TEXT NOT NULL DEFAULT '',
                Tipo          TEXT NOT NULL DEFAULT '',
                Regime        TEXT NOT NULL DEFAULT '',
                Restricao     TEXT NOT NULL DEFAULT '',
                Tarja         TEXT NOT NULL DEFAULT '',
                Destinacao    TEXT NOT NULL DEFAULT '',
                Cap           TEXT NOT NULL DEFAULT '',
                Confaz87      TEXT NOT NULL DEFAULT '',
                PrecosJson    TEXT NOT NULL DEFAULT '{}',
                LinhaOrigem   TEXT NOT NULL DEFAULT '',
                Busca         TEXT NOT NULL DEFAULT ''
            );

            ALTER TABLE CmedProdutos ADD COLUMN IF NOT EXISTS Busca TEXT NOT NULL DEFAULT '';

            CREATE TABLE IF NOT EXISTS CmedEans (
                Ean       TEXT NOT NULL,
                ProdutoId BIGINT NOT NULL REFERENCES CmedProdutos(Id) ON DELETE CASCADE,
                PRIMARY KEY (Ean, ProdutoId)
            );

            CREATE INDEX IF NOT EXISTS IX_CmedEans_Ean ON CmedEans (Ean);
            CREATE INDEX IF NOT EXISTS IX_CmedProdutos_Busca ON CmedProdutos (Busca);
            """);
    }

    public async Task<CmedImportacaoResultado> ImportarCatalogoCmedAsync(
        string caminhoPmc,
        string caminhoPmvg,
        IProgress<string>? progresso = null,
        CancellationToken cancellationToken = default)
    {
        var resultado = await Task.Run(
            () => CmedCatalogoImportador.Ler(caminhoPmc, caminhoPmvg, progresso),
            cancellationToken);

        progresso?.Report("Gravando catalogo...");
        await SubstituirCatalogoCmedAsync(resultado, cancellationToken);
        return resultado;
    }

    public async Task SubstituirCatalogoCmedAsync(
        CmedImportacaoResultado resultado,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);

        try
        {
            await connection.ExecuteAsync(new CommandDefinition(
                "DELETE FROM CmedEans; DELETE FROM CmedProdutos;",
                transaction: transaction,
                cancellationToken: cancellationToken));

            long id = 0;
            await using (var copia = await connection.BeginBinaryImportAsync("""
                COPY CmedProdutos (Id, Registro, Ggrem, Ean1, Ean2, Ean3, Substancia,
                    Laboratorio, Cnpj, Produto, Apresentacao, Classe, Tipo, Regime,
                    Restricao, Tarja, Destinacao, Cap, Confaz87, PrecosJson, LinhaOrigem, Busca)
                FROM STDIN (FORMAT BINARY)
                """, cancellationToken))
            {
                foreach (var produto in resultado.Produtos)
                {
                    id++;
                    produto.Id = id;
                    await copia.StartRowAsync(cancellationToken);
                    await copia.WriteAsync(id, NpgsqlDbType.Bigint, cancellationToken);
                    await copia.WriteAsync(produto.Registro, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Ggrem, NpgsqlDbType.Text, cancellationToken);
                    await EscreverTextoOuNuloAsync(copia, produto.Ean1, cancellationToken);
                    await EscreverTextoOuNuloAsync(copia, produto.Ean2, cancellationToken);
                    await EscreverTextoOuNuloAsync(copia, produto.Ean3, cancellationToken);
                    await copia.WriteAsync(produto.Substancia, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Laboratorio, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Cnpj, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Produto, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Apresentacao, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Classe, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Tipo, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Regime, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Restricao, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Tarja, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Destinacao, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Cap, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Confaz87, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.PrecosJson, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.LinhaOrigem, NpgsqlDbType.Text, cancellationToken);
                    await copia.WriteAsync(produto.Busca, NpgsqlDbType.Text, cancellationToken);
                }

                await copia.CompleteAsync(cancellationToken);
            }

            await using (var copiaEan = await connection.BeginBinaryImportAsync(
                "COPY CmedEans (Ean, ProdutoId) FROM STDIN (FORMAT BINARY)",
                cancellationToken))
            {
                foreach (var produto in resultado.Produtos)
                {
                    foreach (var ean in produto.Eans().Distinct(StringComparer.Ordinal))
                    {
                        await copiaEan.StartRowAsync(cancellationToken);
                        await copiaEan.WriteAsync(ean, NpgsqlDbType.Text, cancellationToken);
                        await copiaEan.WriteAsync(produto.Id, NpgsqlDbType.Bigint, cancellationToken);
                    }
                }

                await copiaEan.CompleteAsync(cancellationToken);
            }

            await connection.ExecuteAsync(new CommandDefinition(
                "SELECT setval(pg_get_serial_sequence('cmedprodutos', 'id'), @Id, true)",
                new { Id = Math.Max(1, id) },
                transaction,
                cancellationToken: cancellationToken));

            var agora = DateTime.Now.ToString("dd/MM/yyyy HH:mm");
            var metadados = new (string Chave, string Valor)[]
            {
                (CmedChavePublicacao, resultado.Publicacao),
                (CmedChaveImportadoEm, agora),
                (CmedChaveFontePmc, resultado.FontePmc),
                (CmedChaveFontePmvg, resultado.FontePmvg),
                (CmedChaveTotalProdutos, resultado.Produtos.Count.ToString()),
                (CmedChaveTotalEans, resultado.TotalParesEan.ToString()),
                (CmedChaveAliquotas, JsonSerializer.Serialize(resultado.Aliquotas))
            };

            foreach (var (chave, valor) in metadados)
            {
                await connection.ExecuteAsync(new CommandDefinition("""
                    INSERT INTO AppConfig (Chave, Valor)
                    VALUES (@Chave, @Valor)
                    ON CONFLICT (Chave) DO UPDATE SET Valor = EXCLUDED.Valor
                    """,
                    new { Chave = chave, Valor = valor },
                    transaction,
                    cancellationToken: cancellationToken));
            }

            await transaction.CommitAsync(cancellationToken);
        }
        catch
        {
            await transaction.RollbackAsync(CancellationToken.None);
            throw;
        }
    }

    private static async Task EscreverTextoOuNuloAsync(
        NpgsqlBinaryImporter copia,
        string? valor,
        CancellationToken cancellationToken)
    {
        if (string.IsNullOrEmpty(valor))
            await copia.WriteNullAsync(cancellationToken);
        else
            await copia.WriteAsync(valor, NpgsqlDbType.Text, cancellationToken);
    }

    public sealed record CmedMetadados(
        bool Importado,
        string Publicacao,
        string ImportadoEm,
        int TotalProdutos,
        IReadOnlyList<string> Aliquotas,
        string FontePmc);

    private sealed class CmedConfigItem
    {
        public string Chave { get; set; } = string.Empty;
        public string Valor { get; set; } = string.Empty;
    }

    public async Task<CmedMetadados> ObterCmedMetadadosAsync(CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var valores = (await connection.QueryAsync<CmedConfigItem>(new CommandDefinition(
                "SELECT Chave, Valor FROM AppConfig WHERE Chave LIKE 'Cmed.%'",
                cancellationToken: cancellationToken)))
            .ToDictionary(x => x.Chave, x => x.Valor, StringComparer.Ordinal);

        var total = await connection.ExecuteScalarAsync<long>(new CommandDefinition(
            "SELECT COUNT(*) FROM CmedProdutos",
            cancellationToken: cancellationToken));

        var aliquotas = new List<string>();
        if (valores.TryGetValue(CmedChaveAliquotas, out var json) && !string.IsNullOrWhiteSpace(json))
        {
            try
            {
                aliquotas = JsonSerializer.Deserialize<List<string>>(json) ?? [];
            }
            catch (JsonException)
            {
                aliquotas = [];
            }
        }

        return new CmedMetadados(
            total > 0,
            valores.GetValueOrDefault(CmedChavePublicacao) ?? string.Empty,
            valores.GetValueOrDefault(CmedChaveImportadoEm) ?? string.Empty,
            (int)total,
            aliquotas,
            valores.GetValueOrDefault(CmedChaveFontePmc) ?? string.Empty);
    }

    public async Task<IReadOnlyList<CmedConsultaResultado>> ConsultarCmedAsync(
        string termo,
        string aliquota,
        int limite = 100,
        CancellationToken cancellationToken = default)
    {
        var texto = (termo ?? string.Empty).Trim();
        if (texto.Length == 0)
            return [];

        var digitos = new string(texto.Where(char.IsDigit).ToArray());
        var somenteNumero = digitos.Length >= 8 && texto.All(c => char.IsDigit(c) || char.IsWhiteSpace(c));

        IReadOnlyList<CmedProduto> produtos = somenteNumero
            ? await BuscarCmedPorEanAsync(digitos, cancellationToken)
            : await BuscarCmedPorTextoAsync(texto, limite, cancellationToken);

        return produtos.Select(p => MontarResultadoCmed(p, aliquota)).ToList();
    }

    private async Task<IReadOnlyList<CmedProduto>> BuscarCmedPorEanAsync(
        string ean,
        CancellationToken cancellationToken)
    {
        var limpo = CmedTexto.NormalizarEan(ean);
        if (limpo is null)
            return [];

        var candidatos = new List<string> { limpo, limpo.TrimStart('0') };
        if (limpo.Length <= 13)
            candidatos.Add(limpo.PadLeft(13, '0'));

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var linhas = await connection.QueryAsync<CmedProduto>(new CommandDefinition("""
            SELECT DISTINCT p.*
            FROM CmedEans e
            JOIN CmedProdutos p ON p.Id = e.ProdutoId
            WHERE e.Ean = ANY(@Eans) OR ltrim(e.Ean, '0') = ANY(@Eans)
            ORDER BY p.Produto, p.Apresentacao
            """,
            new { Eans = candidatos.Where(c => c.Length > 0).Distinct(StringComparer.Ordinal).ToArray() },
            cancellationToken: cancellationToken));

        return linhas.ToList();
    }

    private async Task<IReadOnlyList<CmedProduto>> BuscarCmedPorTextoAsync(
        string texto,
        int limite,
        CancellationToken cancellationToken)
    {
        var termos = CmedTexto.NormalizarCabecalho(texto)
            .ToLowerInvariant()
            .Split(' ', StringSplitOptions.RemoveEmptyEntries)
            .Where(t => t.Length >= 2)
            .Take(6)
            .Select(t => t.Replace("%", "").Replace("_", ""))
            .Where(t => t.Length >= 2)
            .ToList();

        if (termos.Count == 0)
            return [];

        var parametros = new DynamicParameters();
        var condicoes = new List<string>();
        for (var indice = 0; indice < termos.Count; indice++)
        {
            parametros.Add($"T{indice}", $"%{termos[indice]}%");
            condicoes.Add($"Busca LIKE @T{indice}");
        }

        parametros.Add("Limite", Math.Clamp(limite, 1, 300));
        var sql = $"""
            SELECT * FROM CmedProdutos
            WHERE {string.Join(" AND ", condicoes)}
            ORDER BY Produto, Apresentacao
            LIMIT @Limite
            """;

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        var linhas = await connection.QueryAsync<CmedProduto>(
            new CommandDefinition(sql, parametros, cancellationToken: cancellationToken));
        return linhas.ToList();
    }

    private static CmedConsultaResultado MontarResultadoCmed(CmedProduto produto, string aliquota)
    {
        var precos = CmedPrecos.Desserializar(produto.PrecosJson);
        return new CmedConsultaResultado
        {
            Produto = produto,
            Aliquota = aliquota,
            Pf = precos.Obter(CmedPrecos.TipoPf, aliquota),
            Pmc = precos.Obter(CmedPrecos.TipoPmc, aliquota),
            Pmvg = precos.Obter(CmedPrecos.TipoPmvg, aliquota),
            Controle = CmedTarja.Rotulo(produto.Tarja)
        };
    }
