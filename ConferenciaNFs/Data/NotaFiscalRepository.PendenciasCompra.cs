    private static void InicializarTabelaPendenciasCompra(NpgsqlConnection connection)
    {
        connection.Execute("""
            CREATE TABLE IF NOT EXISTS PendenciasCompra (
                Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                NotaFiscalId BIGINT NOT NULL REFERENCES NotasFiscais(Id),
                PessoaId BIGINT NOT NULL REFERENCES Pessoas(Id),
                Observacao TEXT NOT NULL DEFAULT '',
                StatusPendencia TEXT NOT NULL DEFAULT 'Aberta',
                CriadaEm TEXT NOT NULL DEFAULT ''
            );

            CREATE INDEX IF NOT EXISTS IX_PendenciasCompra_NotaFiscalId
                ON PendenciasCompra (NotaFiscalId);

            ALTER TABLE PendenciasCompra ADD COLUMN IF NOT EXISTS RespondidaEm TEXT NOT NULL DEFAULT '';
            ALTER TABLE PendenciasCompra ADD COLUMN IF NOT EXISTS EnviadoPorPessoaId BIGINT NULL REFERENCES Pessoas(Id);
            ALTER TABLE PendenciasCompra ADD COLUMN IF NOT EXISTS EnviadoPorNome TEXT NOT NULL DEFAULT '';

            CREATE TABLE IF NOT EXISTS PendenciaCompraItens (
                Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                PendenciaId BIGINT NOT NULL REFERENCES PendenciasCompra(Id) ON DELETE CASCADE,
                NotaFiscalId BIGINT NOT NULL,
                Sequencia INTEGER NOT NULL,
                CodProd INTEGER NOT NULL DEFAULT 0,
                NomeProd TEXT NOT NULL DEFAULT '',
                BarrasEan TEXT NOT NULL DEFAULT '',
                Quantidade NUMERIC(18,4) NOT NULL,
                CustoNota NUMERIC(18,4) NOT NULL DEFAULT 0,
                UNIQUE (PendenciaId, Sequencia)
            );
            """);
    }

    /// <summary>
    /// Amarelo só da conferência: pinta a nota e encerra pendência aberta, sem criar outra.
    /// Não mexe em devolução concluída.
    /// </summary>
    public async Task DeixarAmareloSomenteConferenciaAsync(
        long notaFiscalId,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var tx = await connection.BeginTransactionAsync(cancellationToken);

        await PintarAmareloAsync(connection, tx, notaFiscalId, "Operador", cancellationToken);
        await connection.ExecuteAsync(new CommandDefinition(
            """
            UPDATE PendenciasCompra
            SET StatusPendencia = @Cancelada
            WHERE NotaFiscalId = @NotaFiscalId
              AND StatusPendencia = @Aberta
            """,
            new
            {
                NotaFiscalId = notaFiscalId,
                Cancelada = StatusPendenciaCompraValues.Cancelada,
                Aberta = StatusPendenciaCompraValues.Aberta
            },
            tx,
            cancellationToken: cancellationToken));

        await tx.CommitAsync(cancellationToken);
    }

    /// <summary>
    /// Grava a pré-nota de divergência e só então pinta a nota de Amarelo.
    /// Não entra na fila de devoluções.
    /// </summary>
    public async Task RegistrarPendenciaDivergenciaAsync(
        long notaFiscalId,
        long pessoaId,
        string? observacao,
        IReadOnlyList<PendenciaCompraItem> itens,
        long enviadoPorPessoaId = 0,
        CancellationToken cancellationToken = default)
    {
        if (pessoaId <= 0)
            throw new InvalidOperationException("Escolha a pessoa que vai receber a divergencia.");

        if (itens.Count == 0)
            throw new InvalidOperationException("Selecione ao menos um produto.");

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var tx = await connection.BeginTransactionAsync(cancellationToken);

        var pessoaAtiva = await connection.ExecuteScalarAsync<bool?>(new CommandDefinition(
            "SELECT Ativo FROM Pessoas WHERE Id = @Id",
            new { Id = pessoaId },
            tx,
            cancellationToken: cancellationToken));

        if (pessoaAtiva is not true)
            throw new InvalidOperationException("Escolha uma pessoa ativa do cadastro.");

        await PintarAmareloAsync(connection, tx, notaFiscalId, "Divergencia", cancellationToken);

        var abertaId = await connection.QuerySingleOrDefaultAsync<long?>(new CommandDefinition(
            """
            SELECT Id
            FROM PendenciasCompra
            WHERE NotaFiscalId = @NotaFiscalId
              AND StatusPendencia = @Aberta
            ORDER BY Id DESC
            LIMIT 1
            """,
            new
            {
                NotaFiscalId = notaFiscalId,
                Aberta = StatusPendenciaCompraValues.Aberta
            },
            tx,
            cancellationToken: cancellationToken));

        var texto = (observacao ?? string.Empty).Trim();
        long pendenciaId;
        if (abertaId is long existente)
        {
            pendenciaId = existente;
            await connection.ExecuteAsync(new CommandDefinition(
                """
                UPDATE PendenciasCompra
                SET PessoaId = @PessoaId,
                    Observacao = @Observacao
                WHERE Id = @Id
                """,
                new { Id = pendenciaId, PessoaId = pessoaId, Observacao = texto },
                tx,
                cancellationToken: cancellationToken));

            await connection.ExecuteAsync(new CommandDefinition(
                "DELETE FROM PendenciaCompraItens WHERE PendenciaId = @PendenciaId",
                new { PendenciaId = pendenciaId },
                tx,
                cancellationToken: cancellationToken));
        }
        else
        {
            if (enviadoPorPessoaId <= 0)
                throw new InvalidOperationException(
                    "Escolha quem usa este PC no menu antes de enviar a divergencia.");

            var enviadoPorNome = await connection.QuerySingleOrDefaultAsync<string>(new CommandDefinition(
                """
                SELECT Nome
                FROM Pessoas
                WHERE Id = @Id
                  AND Ativo = TRUE
                """,
                new { Id = enviadoPorPessoaId },
                tx,
                cancellationToken: cancellationToken));

            if (string.IsNullOrWhiteSpace(enviadoPorNome))
                throw new InvalidOperationException(
                    "A pessoa deste PC nao esta ativa. Escolha outra no menu.");

            var criadaEm = DateTime.Now.ToString("dd/MM/yyyy HH:mm", CultureInfo.GetCultureInfo("pt-BR"));
            pendenciaId = await connection.ExecuteScalarAsync<long>(new CommandDefinition(
                """
                INSERT INTO PendenciasCompra (
                    NotaFiscalId, PessoaId, Observacao, StatusPendencia, CriadaEm,
                    EnviadoPorPessoaId, EnviadoPorNome)
                VALUES (
                    @NotaFiscalId, @PessoaId, @Observacao, @Aberta, @CriadaEm,
                    @EnviadoPorPessoaId, @EnviadoPorNome)
                RETURNING Id
                """,
                new
                {
                    NotaFiscalId = notaFiscalId,
                    PessoaId = pessoaId,
                    Observacao = texto,
                    Aberta = StatusPendenciaCompraValues.Aberta,
                    CriadaEm = criadaEm,
                    EnviadoPorPessoaId = enviadoPorPessoaId,
                    EnviadoPorNome = enviadoPorNome
                },
                tx,
                cancellationToken: cancellationToken));
        }

        foreach (var item in itens)
        {
            await connection.ExecuteAsync(new CommandDefinition(
                """
                INSERT INTO PendenciaCompraItens (
                    PendenciaId, NotaFiscalId, Sequencia, CodProd, NomeProd,
                    BarrasEan, Quantidade, CustoNota)
                VALUES (
                    @PendenciaId, @NotaFiscalId, @Sequencia, @CodProd, @NomeProd,
                    @BarrasEan, @Quantidade, @CustoNota)
                """,
                new
                {
                    PendenciaId = pendenciaId,
                    NotaFiscalId = notaFiscalId,
                    item.Sequencia,
                    item.CodProd,
                    item.NomeProd,
                    item.BarrasEan,
                    item.Quantidade,
                    item.CustoNota
                },
                tx,
                cancellationToken: cancellationToken));
        }

        await tx.CommitAsync(cancellationToken);
    }

    /// <summary>
    /// Ficar: a nota volta Verde com a observação. Devolver: entra na fila existente, sem apagar devolução concluída.
    /// A pendência muda de status e permanece.
    /// </summary>
    public async Task<string> ResponderPendenciaAsync(
        long pendenciaId,
        bool ficarComDivergencia,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var tx = await connection.BeginTransactionAsync(cancellationToken);

        var pendencia = await connection.QuerySingleOrDefaultAsync<PendenciaRespostaRow>(
            new CommandDefinition(
                """
                SELECT NotaFiscalId, Observacao, StatusPendencia
                FROM PendenciasCompra
                WHERE Id = @Id
                """,
                new { Id = pendenciaId },
                tx,
                cancellationToken: cancellationToken));

        if (pendencia is null)
            throw new InvalidOperationException("Divergencia nao encontrada.");

        if (!PendenciaConferenciaLeitura.ApareceNaLista(pendencia.StatusPendencia))
            throw new InvalidOperationException("Esta divergencia ja foi respondida.");

        var nota = await connection.QuerySingleOrDefaultAsync<NotaRespostaRow>(
            new CommandDefinition(
                """
                SELECT Observacao, StatusConferencia
                FROM NotasFiscais
                WHERE Id = @Id
                """,
                new { Id = pendencia.NotaFiscalId },
                tx,
                cancellationToken: cancellationToken));

        if (nota is null)
            throw new InvalidOperationException($"Nota com Id {pendencia.NotaFiscalId} nao encontrada.");

        var observacao = PendenciaConferenciaLeitura.JuntarObservacao(nota.Observacao, pendencia.Observacao);
        var statusNota = RespostaPendenciaEfeito.StatusNota(ficarComDivergencia);

        if (RespostaPendenciaEfeito.EntraNaFilaDevolucao(ficarComDivergencia))
        {
            var itens = (await connection.QueryAsync<PendenciaCompraItem>(new CommandDefinition(
                """
                SELECT PendenciaId, Sequencia, CodProd, NomeProd, BarrasEan, Quantidade, CustoNota
                FROM PendenciaCompraItens
                WHERE PendenciaId = @PendenciaId
                ORDER BY Sequencia
                """,
                new { PendenciaId = pendenciaId },
                tx,
                cancellationToken: cancellationToken))).AsList();

            if (itens.Count == 0)
                throw new InvalidOperationException("Esta divergencia nao tem itens para devolver.");

            statusNota = await EnviarParaFilaDevolucaoAsync(
                connection,
                tx,
                pendencia.NotaFiscalId,
                observacao,
                itens,
                cancellationToken);
        }

        await connection.ExecuteAsync(new CommandDefinition(
            """
            UPDATE NotasFiscais
            SET StatusConferencia = @Status,
                Observacao = @Observacao,
                OrigemStatus = @OrigemStatus,
                StatusHerdadoDeNotaFiscalId = NULL,
                StatusAtualizadoPor = @StatusAtualizadoPor
            WHERE Id = @Id
            """,
            new
            {
                Id = pendencia.NotaFiscalId,
                Status = statusNota,
                Observacao = observacao,
                OrigemStatus = OrigemStatusValues.Manual,
                StatusAtualizadoPor = "Divergencia"
            },
            tx,
            cancellationToken: cancellationToken));

        var respondidaEm = DateTime.Now.ToString("dd/MM/yyyy HH:mm", CultureInfo.GetCultureInfo("pt-BR"));
        var atualizadas = await connection.ExecuteAsync(new CommandDefinition(
            """
            UPDATE PendenciasCompra
            SET StatusPendencia = @Status,
                RespondidaEm = @RespondidaEm
            WHERE Id = @Id
              AND StatusPendencia = @Aberta
            """,
            new
            {
                Id = pendenciaId,
                Status = RespostaPendenciaEfeito.StatusPendencia(ficarComDivergencia),
                RespondidaEm = respondidaEm,
                Aberta = StatusPendenciaCompraValues.Aberta
            },
            tx,
            cancellationToken: cancellationToken));

        if (atualizadas == 0)
            throw new InvalidOperationException("Esta divergencia ja foi respondida.");

        await tx.CommitAsync(cancellationToken);
        return statusNota;
    }

    private static async Task<string> EnviarParaFilaDevolucaoAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction tx,
        long notaFiscalId,
        string observacao,
        IReadOnlyList<PendenciaCompraItem> itens,
        CancellationToken cancellationToken)
    {
        var devolucaoId = await RegistrarDevolucaoPendenteAsync(connection, tx, notaFiscalId, cancellationToken);
        if (devolucaoId <= 0)
            throw new InvalidOperationException("Nao foi possivel incluir a nota na fila de devolucoes.");

        var dona = await connection.QuerySingleAsync<DevolucaoDonaRow>(
            new CommandDefinition(
                """
                SELECT NotaFiscalId, StatusDevolucao
                FROM Devolucoes
                WHERE Id = @Id
                """,
                new { Id = devolucaoId },
                tx,
                cancellationToken: cancellationToken));

        if (!string.Equals(dona.StatusDevolucao, StatusDevolucaoValues.Pendente, StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("Esta nota ja tem devolucao concluida. Nada foi alterado.");

        var sequencias = (await connection.QueryAsync<int>(new CommandDefinition(
            """
            SELECT Sequencia
            FROM DevolucaoItens
            WHERE DevolucaoId = @DevolucaoId
            """,
            new { DevolucaoId = devolucaoId },
            tx,
            cancellationToken: cancellationToken))).ToHashSet();

        foreach (var item in itens)
        {
            if (!sequencias.Add(item.Sequencia))
                continue;

            await connection.ExecuteAsync(new CommandDefinition(
                """
                INSERT INTO DevolucaoItens (
                    DevolucaoId, NotaFiscalId, Sequencia, CodProd, NomeProd,
                    BarrasEan, Quantidade, CustoNota, Motivo, Classe)
                VALUES (
                    @DevolucaoId, @NotaFiscalId, @Sequencia, @CodProd, @NomeProd,
                    @BarrasEan, @Quantidade, @CustoNota, @Motivo, @Classe)
                """,
                new
                {
                    DevolucaoId = devolucaoId,
                    NotaFiscalId = notaFiscalId,
                    item.Sequencia,
                    item.CodProd,
                    item.NomeProd,
                    item.BarrasEan,
                    item.Quantidade,
                    item.CustoNota,
                    Motivo = "Divergencia",
                    Classe = string.Empty
                },
                tx,
                cancellationToken: cancellationToken));
        }

        await connection.ExecuteAsync(new CommandDefinition(
            """
            UPDATE Devolucoes
            SET Observacao = @Observacao
            WHERE Id = @Id
              AND StatusDevolucao = @Pendente
              AND TRIM(COALESCE(Observacao, '')) = ''
            """,
            new
            {
                Id = devolucaoId,
                Observacao = observacao,
                Pendente = StatusDevolucaoValues.Pendente
            },
            tx,
            cancellationToken: cancellationToken));

        return dona.NotaFiscalId == notaFiscalId
            ? StatusConferenciaValues.Vermelho
            : StatusConferenciaValues.Laranja;
    }

    public async Task<IReadOnlyList<PendenciaAviso>> ListarAvisosPendenciaAsync(
        long pessoaId,
        CancellationToken cancellationToken = default)
    {
        if (pessoaId <= 0)
            return [];

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var linhas = await connection.QueryAsync<PendenciaAviso>(new CommandDefinition(
            """
            SELECT
                p.Id,
                n.NumNota,
                n.ApelidoLoja,
                p.EnviadoPorNome
            FROM PendenciasCompra p
            INNER JOIN NotasFiscais n ON n.Id = p.NotaFiscalId
            WHERE p.StatusPendencia = @Aberta
              AND p.PessoaId = @PessoaId
            ORDER BY p.Id
            """,
            new
            {
                Aberta = StatusPendenciaCompraValues.Aberta,
                PessoaId = pessoaId
            },
            cancellationToken: cancellationToken));

        return linhas.AsList();
    }

    public async Task<IReadOnlyList<PendenciaAviso>> ListarResolucoesPendenciaAsync(
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var linhas = await connection.QueryAsync<PendenciaAviso>(new CommandDefinition(
            """
            SELECT
                p.Id,
                n.NumNota,
                n.ApelidoLoja,
                p.EnviadoPorNome,
                p.StatusPendencia
            FROM PendenciasCompra p
            INNER JOIN NotasFiscais n ON n.Id = p.NotaFiscalId
            WHERE p.StatusPendencia = ANY(@Statuses)
            ORDER BY p.Id
            """,
            new
            {
                Statuses = new[]
                {
                    StatusPendenciaCompraValues.Ficou,
                    StatusPendenciaCompraValues.Devolvida
                }
            },
            cancellationToken: cancellationToken));

        return linhas.AsList();
    }

    public async Task<IReadOnlyList<PendenciaCompraResumo>> ListarPendenciasAsync(
        bool concluidas,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var linhas = (await connection.QueryAsync<PendenciaCompraResumo>(new CommandDefinition(
            """
            SELECT
                p.Id,
                p.NotaFiscalId,
                pe.Nome AS PessoaNome,
                p.EnviadoPorNome,
                n.ApelidoLoja,
                n.NumNota,
                n.DiaConferencia,
                n.NomeForn,
                p.Observacao,
                p.StatusPendencia,
                p.CriadaEm,
                p.RespondidaEm
            FROM PendenciasCompra p
            INNER JOIN NotasFiscais n ON n.Id = p.NotaFiscalId
            INNER JOIN Pessoas pe ON pe.Id = p.PessoaId
            WHERE p.StatusPendencia = ANY(@Statuses)
            ORDER BY p.Id DESC
            """,
            new
            {
                Statuses = concluidas
                    ? new[] { StatusPendenciaCompraValues.Ficou, StatusPendenciaCompraValues.Devolvida }
                    : new[] { StatusPendenciaCompraValues.Aberta }
            },
            cancellationToken: cancellationToken))).AsList();

        await PreencherItensAsync(connection, linhas, cancellationToken);
        return linhas;
    }

    public async Task<PendenciaCompraResumo?> ObterPendenciaAsync(
        long pendenciaId,
        CancellationToken cancellationToken = default)
    {
        if (pendenciaId <= 0)
            return null;

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var pendencia = await connection.QuerySingleOrDefaultAsync<PendenciaCompraResumo>(new CommandDefinition(
            """
            SELECT
                p.Id,
                p.NotaFiscalId,
                p.PessoaId,
                pe.Nome AS PessoaNome,
                p.EnviadoPorNome,
                n.ApelidoLoja,
                n.NumNota,
                n.DiaConferencia,
                n.NomeForn,
                p.Observacao,
                p.StatusPendencia,
                p.CriadaEm,
                p.RespondidaEm
            FROM PendenciasCompra p
            INNER JOIN NotasFiscais n ON n.Id = p.NotaFiscalId
            INNER JOIN Pessoas pe ON pe.Id = p.PessoaId
            WHERE p.Id = @Id
            """,
            new { Id = pendenciaId },
            cancellationToken: cancellationToken));

        if (pendencia is null)
            return null;

        var itens = (await connection.QueryAsync<PendenciaCompraItem>(new CommandDefinition(
            """
            SELECT PendenciaId, Sequencia, CodProd, NomeProd, BarrasEan, Quantidade, CustoNota
            FROM PendenciaCompraItens
            WHERE PendenciaId = @PendenciaId
            ORDER BY Sequencia
            """,
            new { PendenciaId = pendenciaId },
            cancellationToken: cancellationToken))).AsList();

        pendencia.Itens = itens;
        pendencia.ItensTexto = PendenciaConferenciaLeitura.TextoItens(itens);
        return pendencia;
    }

    public async Task<IReadOnlyDictionary<long, PendenciaCompraResumo>> ObterPendenciasAbertasPorNotasAsync(
        IReadOnlyList<long> notaFiscalIds,
        CancellationToken cancellationToken = default)
    {
        if (notaFiscalIds.Count == 0)
            return new Dictionary<long, PendenciaCompraResumo>();

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var linhas = (await connection.QueryAsync<PendenciaCompraResumo>(new CommandDefinition(
            """
            SELECT
                p.Id,
                p.NotaFiscalId,
                pe.Nome AS PessoaNome,
                p.EnviadoPorNome,
                n.ApelidoLoja,
                n.NumNota,
                n.DiaConferencia,
                n.NomeForn,
                p.Observacao,
                p.StatusPendencia,
                p.CriadaEm,
                p.RespondidaEm
            FROM PendenciasCompra p
            INNER JOIN NotasFiscais n ON n.Id = p.NotaFiscalId
            INNER JOIN Pessoas pe ON pe.Id = p.PessoaId
            WHERE p.StatusPendencia = @Aberta
              AND p.NotaFiscalId = ANY(@Ids)
            """,
            new
            {
                Aberta = StatusPendenciaCompraValues.Aberta,
                Ids = notaFiscalIds.Distinct().ToArray()
            },
            cancellationToken: cancellationToken))).AsList();

        await PreencherItensAsync(connection, linhas, cancellationToken);
        return linhas
            .GroupBy(p => p.NotaFiscalId)
            .ToDictionary(g => g.Key, g => g.OrderByDescending(p => p.Id).First());
    }

    private static async Task PreencherItensAsync(
        NpgsqlConnection connection,
        List<PendenciaCompraResumo> pendencias,
        CancellationToken cancellationToken)
    {
        if (pendencias.Count == 0)
            return;

        var itens = (await connection.QueryAsync<PendenciaCompraItem>(new CommandDefinition(
            """
            SELECT PendenciaId, Sequencia, CodProd, NomeProd, BarrasEan, Quantidade, CustoNota
            FROM PendenciaCompraItens
            WHERE PendenciaId = ANY(@Ids)
            ORDER BY Sequencia
            """,
            new { Ids = pendencias.Select(p => p.Id).Distinct().ToArray() },
            cancellationToken: cancellationToken))).AsList();

        var porPendencia = itens.GroupBy(i => i.PendenciaId).ToDictionary(g => g.Key, g => g.ToList());
        foreach (var pendencia in pendencias)
        {
            pendencia.ItensTexto = porPendencia.TryGetValue(pendencia.Id, out var daPendencia)
                ? PendenciaConferenciaLeitura.TextoItens(daPendencia)
                : string.Empty;
        }
    }

    private static async Task PintarAmareloAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        long notaFiscalId,
        string atualizadoPor,
        CancellationToken cancellationToken)
    {
        var statusAtual = await connection.QuerySingleOrDefaultAsync<string>(new CommandDefinition(
            """
            SELECT StatusConferencia
            FROM NotasFiscais
            WHERE Id = @Id
            """,
            new { Id = notaFiscalId },
            transaction,
            cancellationToken: cancellationToken));

        if (statusAtual is null)
            throw new InvalidOperationException($"Nota com Id {notaFiscalId} nao encontrada.");

        await connection.ExecuteAsync(new CommandDefinition(
            """
            UPDATE NotasFiscais
            SET StatusConferencia = @Status,
                OrigemStatus = @OrigemStatus,
                StatusHerdadoDeNotaFiscalId = NULL,
                StatusAtualizadoPor = @StatusAtualizadoPor
            WHERE Id = @Id
            """,
            new
            {
                Id = notaFiscalId,
                Status = StatusConferenciaValues.Amarelo,
                OrigemStatus = OrigemStatusValues.Manual,
                StatusAtualizadoPor = atualizadoPor
            },
            transaction,
            cancellationToken: cancellationToken));

        if (statusAtual == StatusConferenciaValues.Vermelho)
        {
            await connection.ExecuteAsync(new CommandDefinition(
                """
                DELETE FROM Devolucoes
                WHERE NotaFiscalId = @NotaFiscalId
                  AND StatusDevolucao = @StatusPendente
                """,
                new
                {
                    NotaFiscalId = notaFiscalId,
                    StatusPendente = StatusDevolucaoValues.Pendente
                },
                transaction,
                cancellationToken: cancellationToken));
        }
    }

    private sealed class PendenciaRespostaRow
    {
        public long NotaFiscalId { get; set; }
        public string Observacao { get; set; } = string.Empty;
        public string StatusPendencia { get; set; } = string.Empty;
    }

    private sealed class NotaRespostaRow
    {
        public string Observacao { get; set; } = string.Empty;
        public string StatusConferencia { get; set; } = string.Empty;
    }

    private sealed class DevolucaoDonaRow
    {
        public long NotaFiscalId { get; set; }
        public string StatusDevolucao { get; set; } = string.Empty;
    }
}
