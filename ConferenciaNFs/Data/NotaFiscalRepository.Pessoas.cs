using System.Globalization;
using ConferenciaNFs.Infrastructure;
using ConferenciaNFs.Models;
using Dapper;
using Npgsql;

namespace ConferenciaNFs.Data;

public sealed partial class NotaFiscalRepository
{
    private static void InicializarTabelaPessoas(NpgsqlConnection connection)
    {
        connection.Execute("""
            CREATE TABLE IF NOT EXISTS Pessoas (
                Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                Nome TEXT NOT NULL,
                NomeChave TEXT NOT NULL UNIQUE,
                Ativo BOOLEAN NOT NULL DEFAULT TRUE,
                CriadaEm TEXT NOT NULL DEFAULT ''
            );
            """);

        var criadaEm = DateTime.Now.ToString("dd/MM/yyyy HH:mm", CultureInfo.GetCultureInfo("pt-BR"));
        connection.Execute("""
            INSERT INTO Pessoas (Nome, NomeChave, Ativo, CriadaEm)
            VALUES (@Nome, @NomeChave, TRUE, @CriadaEm)
            ON CONFLICT (NomeChave) DO NOTHING
            """, new
        {
            Nome = "Rafael",
            NomeChave = PessoaNome.Chave("Rafael"),
            CriadaEm = criadaEm
        });
    }

    public async Task<IReadOnlyList<Pessoa>> ListarPessoasAsync(
        bool somenteAtivos,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var sql = somenteAtivos
            ? """
              SELECT Id, Nome, Ativo, CriadaEm
              FROM Pessoas
              WHERE Ativo = TRUE
              ORDER BY Nome
              """
            : """
              SELECT Id, Nome, Ativo, CriadaEm
              FROM Pessoas
              ORDER BY Ativo DESC, Nome
              """;

        var linhas = await connection.QueryAsync<Pessoa>(new CommandDefinition(
            sql,
            cancellationToken: cancellationToken));
        return linhas.AsList();
    }

    public async Task SalvarPessoaAsync(
        string nome,
        CancellationToken cancellationToken = default)
    {
        var exibicao = PessoaNome.NormalizarExibicao(nome);
        if (!PessoaNome.EhValido(exibicao))
            throw new InvalidOperationException("Informe o nome com pelo menos 2 caracteres.");

        var chave = PessoaNome.Chave(exibicao);

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var existente = await connection.QuerySingleOrDefaultAsync<Pessoa>(new CommandDefinition(
            """
            SELECT Id, Nome, Ativo, CriadaEm
            FROM Pessoas
            WHERE NomeChave = @NomeChave
            """,
            new { NomeChave = chave },
            cancellationToken: cancellationToken));

        if (existente is not null)
        {
            if (existente.Ativo)
                throw new InvalidOperationException("Esta pessoa ja esta cadastrada.");

            await connection.ExecuteAsync(new CommandDefinition(
                """
                UPDATE Pessoas
                SET Nome = @Nome,
                    Ativo = TRUE
                WHERE Id = @Id
                """,
                new { Nome = exibicao, existente.Id },
                cancellationToken: cancellationToken));
            return;
        }

        var criadaEm = DateTime.Now.ToString("dd/MM/yyyy HH:mm", CultureInfo.GetCultureInfo("pt-BR"));
        await connection.ExecuteAsync(new CommandDefinition(
            """
            INSERT INTO Pessoas (Nome, NomeChave, Ativo, CriadaEm)
            VALUES (@Nome, @NomeChave, TRUE, @CriadaEm)
            """,
            new { Nome = exibicao, NomeChave = chave, CriadaEm = criadaEm },
            cancellationToken: cancellationToken));
    }

    public async Task DesativarPessoaAsync(
        long id,
        CancellationToken cancellationToken = default)
    {
        if (id <= 0)
            return;

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await connection.ExecuteAsync(new CommandDefinition(
            "UPDATE Pessoas SET Ativo = FALSE WHERE Id = @Id",
            new { Id = id },
            cancellationToken: cancellationToken));
    }
}
