    public async Task<PrecoTabelaImportacao> ImportarTabelaPrecosAsync(
        string nome,
        IReadOnlyList<PrecoTabelaItem> itens,
        CancellationToken cancellationToken = default)
    {
        var nomeLimpo = (nome ?? string.Empty).Trim().ToUpperInvariant();
        if (string.IsNullOrWhiteSpace(nomeLimpo))
            throw new InvalidOperationException("Informe um nome para a importacao.");
        if (itens.Count == 0)
            throw new InvalidOperationException("Nenhum item valido encontrado na planilha.");

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var tx = await connection.BeginTransactionAsync(cancellationToken);

        var jaExiste = await connection.ExecuteScalarAsync<int>(new CommandDefinition(
            "SELECT COUNT(*) FROM PrecosImportacoes WHERE Nome = @Nome",
            new { Nome = nomeLimpo },
            tx,
            cancellationToken: cancellationToken));
        if (jaExiste > 0)
            throw new InvalidOperationException(
                $"Ja existe uma tabela chamada '{nomeLimpo}'. Exclua a anterior antes de importar.");

        var criadaEm = DateTime.Now.ToString("dd/MM/yyyy HH:mm", CultureInfo.GetCultureInfo("pt-BR"));
        var id = await connection.ExecuteScalarAsync<long>(new CommandDefinition(
            """
            INSERT INTO PrecosImportacoes (Nome, CriadaEm)
            VALUES (@Nome, @CriadaEm)
            RETURNING Id
            """,
            new { Nome = nomeLimpo, CriadaEm = criadaEm },
            tx,
            cancellationToken: cancellationToken));

        await connection.ExecuteAsync(new CommandDefinition(
            """
            INSERT INTO PrecosItens (ImportacaoId, Ean, NomeProd, PrecoPrimario, PrecoSecundario)
            VALUES (@ImportacaoId, @Ean, @NomeProd, @PrecoPrimario, @PrecoSecundario)
            """,
            itens.Select(i => new
            {
                ImportacaoId = id,
                i.Ean,
                i.NomeProd,
                i.PrecoPrimario,
                i.PrecoSecundario
            }),
            tx,
            cancellationToken: cancellationToken));

        await tx.CommitAsync(cancellationToken);

        return new PrecoTabelaImportacao
        {
            Id = id,
            Nome = nomeLimpo,
            CriadaEm = criadaEm,
            QuantidadeItens = itens.Count
        };
    }

