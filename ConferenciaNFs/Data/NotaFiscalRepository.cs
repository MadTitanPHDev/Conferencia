    public async Task<int> LimparNotasDoDiaAtualAsync(
        string diaConferencia,
        CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(diaConferencia))
            throw new ArgumentException("Dia de conferencia invalido.", nameof(diaConferencia));

        var data = DataCompraParser.TentarConverter(diaConferencia);
        if (!data.HasValue || data.Value.Date != DateTime.Today)
            throw new InvalidOperationException("So e permitido limpar notas do dia atual.");

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);

        await connection.ExecuteAsync("""
            DELETE FROM Devolucoes d
            USING NotasFiscais n
            WHERE d.NotaFiscalId = n.Id
              AND n.DiaConferencia = @DiaConferencia
            """, new { DiaConferencia = diaConferencia }, transaction);

        var removidas = await connection.ExecuteAsync("""
            DELETE FROM NotasFiscais
            WHERE DiaConferencia = @DiaConferencia
            """, new { DiaConferencia = diaConferencia }, transaction);

        await transaction.CommitAsync(cancellationToken);
        return removidas;
    }

    public async Task AtualizarStatusConferenciaAsync(
        long id,
        string status,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);

        var statusAtual = await connection.QuerySingleOrDefaultAsync<string>("""
            SELECT StatusConferencia
            FROM NotasFiscais
            WHERE Id = @Id
            """, new { Id = id }, transaction);

        if (statusAtual is null)
            throw new InvalidOperationException($"Nota com Id {id} nao encontrada.");

        await connection.ExecuteAsync("""
            UPDATE NotasFiscais
            SET StatusConferencia = @Status,
                OrigemStatus = @OrigemStatus,
                StatusHerdadoDeNotaFiscalId = NULL,
                StatusAtualizadoPor = @StatusAtualizadoPor
            WHERE Id = @Id
            """, new
        {
            Id = id,
            Status = status,
            OrigemStatus = OrigemStatusValues.Manual,
            StatusAtualizadoPor = "Operador"
        }, transaction);

        if (status == StatusConferenciaValues.Vermelho
            && statusAtual != StatusConferenciaValues.Vermelho)
        {
            var dataMinima = await ObterDataMinimaDevolucoesInternalAsync(connection, transaction);
            if (FilaAceitaNovosRegistros(dataMinima))
                await RegistrarDevolucaoPendenteAsync(connection, transaction, id, cancellationToken);
        }
        else if (status != StatusConferenciaValues.Vermelho
                 && statusAtual == StatusConferenciaValues.Vermelho)
        {
            // So remove pendencias da fila; devolucoes concluidas permanecem no historico.
            await connection.ExecuteAsync("""
                DELETE FROM Devolucoes
                WHERE NotaFiscalId = @NotaFiscalId
                  AND StatusDevolucao = @StatusPendente
                """, new
            {
                NotaFiscalId = id,
                StatusPendente = StatusDevolucaoValues.Pendente
            }, transaction);
        }

        await transaction.CommitAsync(cancellationToken);
    }

    private static bool FilaAceitaNovosRegistros(DateTime? dataMinima)
    {
        if (!dataMinima.HasValue)
            return true;

        return DateTime.Today >= dataMinima.Value.Date;
    }

    private static bool DevolucaoVisivelNoPeriodo(DevolucaoItem item, DateTime? dataMinima)
    {
        if (!dataMinima.HasValue)
            return true;

        var referencia = item.DataReferenciaRastreio;
        return referencia.HasValue && referencia.Value.Date >= dataMinima.Value.Date;
    }

    private static async Task<long> RegistrarDevolucaoPendenteAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        long notaFiscalId,
        CancellationToken cancellationToken)
    {
        var existente = await connection.QuerySingleOrDefaultAsync<long?>($"""
            SELECT d.Id
            FROM Devolucoes d
            INNER JOIN NotasFiscais n2 ON n2.Id = d.NotaFiscalId
            INNER JOIN NotasFiscais n ON n.Id = @NotaFiscalId
            WHERE {SqlMesmaIdentidadeNotas}
            ORDER BY
                CASE WHEN d.NotaFiscalId = @NotaFiscalId THEN 0 ELSE 1 END,
                d.Id
            LIMIT 1
            """, new { NotaFiscalId = notaFiscalId }, transaction);

        if (existente.HasValue)
            return existente.Value;

        var dataMinima = await ObterDataMinimaDevolucoesInternalAsync(connection, transaction);
        if (!FilaAceitaNovosRegistros(dataMinima))
            return 0;

        var dataMarcada = DataCompraParser.Formatar(DateTime.Today);
        await connection.ExecuteAsync("""
            INSERT INTO Devolucoes (NotaFiscalId, StatusDevolucao, DataMarcada, DataConclusao, Observacao, Andamento)
            VALUES (@NotaFiscalId, @StatusDevolucao, @DataMarcada, NULL, '', @Andamento)
            ON CONFLICT (NotaFiscalId) DO UPDATE SET
                StatusDevolucao = EXCLUDED.StatusDevolucao,
                DataMarcada = EXCLUDED.DataMarcada,
                DataConclusao = NULL
            WHERE Devolucoes.StatusDevolucao = @StatusPendente;
            """, new
        {
            NotaFiscalId = notaFiscalId,
            StatusDevolucao = StatusDevolucaoValues.Pendente,
            StatusPendente = StatusDevolucaoValues.Pendente,
            DataMarcada = dataMarcada,
            Andamento = AndamentoDevolucaoValues.AguardandoLoja
        }, transaction);

        return await connection.QuerySingleAsync<long>(
            "SELECT Id FROM Devolucoes WHERE NotaFiscalId = @NotaFiscalId",
            new { NotaFiscalId = notaFiscalId },
            transaction);
    }

    public async Task<IReadOnlyList<DevolucaoItem>> ObterDevolucoesAsync(
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var resultado = await connection.QueryAsync<DevolucaoItem>($"""
            SELECT
                d.Id,
                d.NotaFiscalId,
                n.ApelidoLoja,
                n.NumNota,
                n.NomeForn,
                n.CnpjForn,
                n.ValorNota,
                n.DataEmissao,
                n.DiaConferencia,
                d.StatusDevolucao,
                COALESCE(NULLIF(TRIM(d.Andamento), ''), 'AguardandoLoja') AS Andamento,
                d.DataMarcada,
                d.DataConclusao,
                d.Observacao,
                dist.PrazoDevolucaoDias,
                COALESCE(dist.RastrearPrazo, FALSE) AS RastrearPrazo
            FROM Devolucoes d
            INNER JOIN NotasFiscais n ON n.Id = d.NotaFiscalId
            {SqlJoinDistribuidoraPorCnpj}
            ORDER BY
                CASE d.StatusDevolucao
                    WHEN 'Pendente' THEN 0
                    WHEN 'Devolvida' THEN 1
                    WHEN 'Absorvido' THEN 1
                    ELSE 2
                END,
                n.DataEmissao,
                n.NomeForn,
                n.NumNota
            """);

        var dataMinima = await ObterDataMinimaDevolucoesInternalAsync(connection, transaction: null);
        var lista = resultado.ToList();
        if (!dataMinima.HasValue)
            return lista;

        return lista
            .Where(d => DevolucaoVisivelNoPeriodo(d, dataMinima))
            .ToList();
    }

