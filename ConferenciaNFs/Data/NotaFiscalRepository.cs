    private static void InicializarTabelaDevolucoes(NpgsqlConnection connection)
    {
        connection.Execute("""
            CREATE TABLE IF NOT EXISTS Devolucoes (
                Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                NotaFiscalId BIGINT NOT NULL UNIQUE,
                StatusDevolucao TEXT NOT NULL DEFAULT 'Pendente',
                DataMarcada TEXT NOT NULL DEFAULT '',
                DataConclusao TEXT NULL,
                Observacao TEXT NOT NULL DEFAULT ''
            );

            CREATE INDEX IF NOT EXISTS IX_Devolucoes_StatusDevolucao
                ON Devolucoes (StatusDevolucao);

            CREATE INDEX IF NOT EXISTS IX_Devolucoes_NotaFiscalId
                ON Devolucoes (NotaFiscalId);
            """);

        // Notas Vermelho entram na fila se ainda nao tiverem registro (respeita data minima por emissao).
        connection.Execute($"""
            INSERT INTO Devolucoes (NotaFiscalId, StatusDevolucao, DataMarcada, Observacao)
            SELECT
                n.Id,
                'Pendente',
                COALESCE(NULLIF(TRIM(n.DiaConferencia), ''), to_char(CURRENT_DATE, 'DD/MM/YYYY')),
                ''
            FROM NotasFiscais n
            LEFT JOIN Devolucoes d ON d.NotaFiscalId = n.Id
            LEFT JOIN AppConfig cfg ON cfg.Chave = '{ConfigDevolucoesDataMinima}'
            WHERE n.StatusConferencia = 'Vermelho'
              AND d.Id IS NULL
              AND (
                cfg.Valor IS NULL OR TRIM(cfg.Valor) = ''
                OR (
                    NULLIF(TRIM(n.DataEmissao), '') IS NOT NULL
                    AND to_date(NULLIF(TRIM(n.DataEmissao), ''), 'DD/MM/YYYY')
                        >= to_date(NULLIF(TRIM(cfg.Valor), ''), 'DD/MM/YYYY')
                )
              );
            """);
    }

    private static void InicializarTabelaDistribuidoras(NpgsqlConnection connection)
    {
        connection.Execute("""
            CREATE TABLE IF NOT EXISTS Distribuidoras (
                CnpjForn TEXT PRIMARY KEY,
                NomeForn TEXT NOT NULL DEFAULT '',
                PrazoDevolucaoDias INTEGER NULL,
                RastrearPrazo BOOLEAN NOT NULL DEFAULT FALSE
            );

            CREATE INDEX IF NOT EXISTS IX_Distribuidoras_NomeForn
                ON Distribuidoras (NomeForn);

            CREATE INDEX IF NOT EXISTS IX_Distribuidoras_RastrearPrazo
                ON Distribuidoras (RastrearPrazo);
            """);

        // Popular a partir de notas ja importadas (sem sobrescrever prazo/rastreio).
        connection.Execute("""
            INSERT INTO Distribuidoras (CnpjForn, NomeForn, PrazoDevolucaoDias, RastrearPrazo)
            SELECT DISTINCT ON (TRIM(CnpjForn))
                TRIM(CnpjForn),
                COALESCE(NULLIF(TRIM(NomeForn), ''), TRIM(CnpjForn)),
                NULL,
                FALSE
            FROM NotasFiscais
            WHERE CnpjForn IS NOT NULL AND TRIM(CnpjForn) <> ''
            ORDER BY TRIM(CnpjForn), Id DESC
            ON CONFLICT (CnpjForn) DO UPDATE SET
                NomeForn = EXCLUDED.NomeForn;
            """);

        // Normaliza CNPJs antigos (com mascara) para apenas digitos.
        connection.Execute("""
            UPDATE Distribuidoras
            SET CnpjForn = regexp_replace(COALESCE(CnpjForn, ''), '[^0-9]', '', 'g')
            WHERE CnpjForn ~ '[^0-9]';
            """);
    }

    private static void InicializarTabelaLojaOrdem(NpgsqlConnection connection)
    {
        connection.Execute("""
            CREATE TABLE IF NOT EXISTS LojaOrdem (
                ApelidoLoja TEXT PRIMARY KEY,
                NumeroOrdem INTEGER NOT NULL UNIQUE,
                NomeExibicao TEXT NOT NULL
            );

            CREATE INDEX IF NOT EXISTS IX_LojaOrdem_NumeroOrdem
                ON LojaOrdem (NumeroOrdem);
            """);

        AjustarAliasesLojaOrdem(connection);

        foreach (var loja in LojaOrdemSeed.LojasPadrao)
        {
            connection.Execute("""
                INSERT INTO LojaOrdem (ApelidoLoja, NumeroOrdem, NomeExibicao)
                VALUES (@ApelidoLoja, @NumeroOrdem, @NomeExibicao)
                ON CONFLICT (ApelidoLoja) DO NOTHING;
                """, loja);
        }
    }

    private static void NormalizarApelidosExistentes(NpgsqlConnection connection)
    {
        var apelidos = connection.Query<string>("SELECT DISTINCT ApelidoLoja FROM NotasFiscais");
        foreach (var apelidoAtual in apelidos)
        {
            var apelidoNormalizado = LojaAliasNormalizer.Normalizar(apelidoAtual);
            if (apelidoNormalizado == apelidoAtual)
                continue;

            connection.Execute("""
                UPDATE NotasFiscais
                SET ApelidoLoja = @ApelidoNovo
                WHERE ApelidoLoja = @ApelidoAtual
                """, new
            {
                ApelidoAtual = apelidoAtual,
                ApelidoNovo = apelidoNormalizado
            });
        }
    }

