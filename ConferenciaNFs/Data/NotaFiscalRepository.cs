    private readonly record struct StatusHerdado(
        string Status,
        string Observacao,
        long FonteNotaFiscalId);

    private static StatusHerdado? ResolverStatusHerdado(
        NpgsqlConnection connection,
        NpgsqlTransaction? transaction,
        string apelidoLoja,
        string numNota,
        string cnpjForn,
        string diaConferenciaAtual,
        string? nfeChaveAcesso,
        int? codCompra = null)
    {
        var historico = TentarResolverHerancaImportacao(
            connection,
            transaction,
            apelidoLoja,
            numNota,
            cnpjForn,
            diaConferenciaAtual,
            nfeChaveAcesso,
            codCompra);

        if (historico.HasValue)
            return new StatusHerdado(
                historico.Value.Status,
                historico.Value.Observacao,
                historico.Value.FonteNotaFiscalId);

        return null;
    }

    private static string? ObterDiaConferenciaAnterior(
        NpgsqlConnection connection,
        NpgsqlTransaction? transaction,
        string diaConferenciaAtual)
    {
        var atual = DataCompraParser.TentarConverter(diaConferenciaAtual);
        if (!atual.HasValue)
            return null;

        var dias = connection.Query<string>("""
            SELECT DISTINCT DiaConferencia
            FROM NotasFiscais
            WHERE TRIM(COALESCE(DiaConferencia, '')) <> ''
              AND DiaConferencia <> @DiaAtual
            """, new { DiaAtual = diaConferenciaAtual.Trim() }, transaction);

        return dias
            .Select(d => (Texto: d, Data: DataCompraParser.TentarConverter(d)))
            .Where(x => x.Data.HasValue && x.Data.Value.Date < atual.Value.Date)
            .OrderByDescending(x => x.Data!.Value)
            .Select(x => x.Texto)
            .FirstOrDefault();
    }

    private static (string Status, string Observacao, long FonteNotaFiscalId)? TentarResolverHerancaImportacao(
        NpgsqlConnection connection,
        NpgsqlTransaction? transaction,
        string apelidoLoja,
        string numNota,
        string cnpjForn,
        string diaConferenciaAtual,
        string? nfeChaveAcesso = null,
        int? codCompra = null)
    {
        var cnpjNormalizado = CnpjNormalizer.Normalizar(cnpjForn);
        var numNotaTrim = numNota.Trim();
        var numNotaNormalizado = NumNotaNormalizer.Normalizar(numNota);
        var chaveNfe = nfeChaveAcesso?.Trim() ?? string.Empty;
        var cod = codCompra.GetValueOrDefault();
        var historico = connection.Query<HistoricoNotaNegocio>("""
            SELECT Id, StatusConferencia, Observacao, DiaConferencia
            FROM NotasFiscais
            WHERE TRIM(COALESCE(DiaConferencia, '')) <> ''
              AND DiaConferencia <> @DiaConferenciaAtual
              AND (
                    (@CodCompra > 0 AND CodCompra = @CodCompra)
                 OR (@ChaveNfe <> '' AND NfeChaveAcesso = @ChaveNfe)
                 OR (
                        ApelidoLoja = @ApelidoLoja
                    AND (NumNota = @NumNota OR NumNota = @NumNotaNorm)
                    AND regexp_replace(COALESCE(CnpjForn, ''), '[^0-9]', '', 'g') = @CnpjForn
                    )
              )
            """, new
        {
            ApelidoLoja = apelidoLoja.Trim(),
            NumNota = numNotaTrim,
            NumNotaNorm = string.IsNullOrEmpty(numNotaNormalizado) ? numNotaTrim : numNotaNormalizado,
            CnpjForn = cnpjNormalizado,
            DiaConferenciaAtual = diaConferenciaAtual.Trim(),
            ChaveNfe = chaveNfe,
            CodCompra = cod
        }, transaction).ToList();

        // Uma nota so pode herdar de dias realmente anteriores. Isso impede que
        // a sincronizacao de um intervalo use acidentalmente uma linha futura.
        var diaAtual = DataCompraParser.TentarConverter(diaConferenciaAtual);
        if (diaAtual.HasValue)
        {
            historico = historico
                .Where(h =>
                {
                    var diaHistorico = DataCompraParser.TentarConverter(h.DiaConferencia);
                    return diaHistorico.HasValue
                        && diaHistorico.Value.Date < diaAtual.Value.Date;
                })
                .ToList();
        }

        if (historico.Count == 0)
            return null;

        var ultima = historico
            .OrderBy(h => h, Comparer<HistoricoNotaNegocio>.Create((a, b) =>
                DataCompraParser.CompararAscendente(a.DiaConferencia, b.DiaConferencia)))
            .Last();

        if (!StatusHerancaImportacao.TemStatusConferido(ultima.StatusConferencia))
            return null;

        var devolucaoJaRegistrada = connection.ExecuteScalar<bool>("""
            SELECT EXISTS (
                SELECT 1
                FROM Devolucoes d
                INNER JOIN NotasFiscais n ON n.Id = d.NotaFiscalId
                WHERE (
                        (@CodCompra > 0 AND n.CodCompra = @CodCompra)
                     OR (@ChaveNfe <> '' AND n.NfeChaveAcesso = @ChaveNfe)
                     OR (
                            n.ApelidoLoja = @ApelidoLoja
                        AND (n.NumNota = @NumNota OR n.NumNota = @NumNotaNorm)
                        AND regexp_replace(COALESCE(n.CnpjForn, ''), '[^0-9]', '', 'g') = @CnpjForn
                        )
                  )
            )
            """, new
        {
            ApelidoLoja = apelidoLoja.Trim(),
            NumNota = numNotaTrim,
            NumNotaNorm = string.IsNullOrEmpty(numNotaNormalizado) ? numNotaTrim : numNotaNormalizado,
            CnpjForn = cnpjNormalizado,
            ChaveNfe = chaveNfe,
            CodCompra = cod
        }, transaction);

        var calculado = StatusHerancaImportacao.Calcular(
            ultima.StatusConferencia,
            ultima.Observacao,
            devolucaoJaRegistrada);
        return (calculado.Status, calculado.Observacao, ultima.Id);
    }

    private static async Task SincronizarDistribuidorasAsync(
        NpgsqlConnection connection,
        IReadOnlyList<NotaFiscal> registros,
        NpgsqlTransaction transaction,
        CancellationToken cancellationToken)
    {
        var porCnpj = registros
            .Where(n => !string.IsNullOrWhiteSpace(n.CnpjForn))
            .GroupBy(n => CnpjNormalizer.Normalizar(n.CnpjForn.Trim()), StringComparer.Ordinal)
            .Select(g => new
            {
                CnpjForn = g.Key,
                NomeForn = NomeFornecedorEscolha.Escolher(g.Select(n => n.NomeForn), g.Key)
            })
            .Where(x => !string.IsNullOrWhiteSpace(x.CnpjForn));

        const string sql = """
            INSERT INTO Distribuidoras (CnpjForn, NomeForn, PrazoDevolucaoDias, RastrearPrazo)
            VALUES (@CnpjForn, @NomeForn, NULL, FALSE)
            ON CONFLICT (CnpjForn) DO UPDATE SET
                NomeForn = CASE
                    WHEN EXCLUDED.NomeForn <> '' THEN EXCLUDED.NomeForn
                    ELSE Distribuidoras.NomeForn
                END;
            """;

        foreach (var item in porCnpj)
        {
            cancellationToken.ThrowIfCancellationRequested();
            await connection.ExecuteAsync(sql, item, transaction);
        }
    }

    public async Task<IReadOnlyList<Distribuidora>> ObterDistribuidorasAsync(
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var resultado = await connection.QueryAsync<Distribuidora>("""
            SELECT CnpjForn, NomeForn, PrazoDevolucaoDias, RastrearPrazo
            FROM Distribuidoras
            ORDER BY NomeForn, CnpjForn
            """);

        return resultado.ToList();
    }

    public async Task AtualizarDistribuidoraAsync(
        string cnpjForn,
        int? prazoDevolucaoDias,
        bool rastrearPrazo,
        CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(cnpjForn))
            throw new ArgumentException("CNPJ da distribuidora e obrigatorio.", nameof(cnpjForn));

        if (prazoDevolucaoDias is < 0)
            throw new ArgumentOutOfRangeException(nameof(prazoDevolucaoDias), "Prazo nao pode ser negativo.");

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var linhas =         await connection.ExecuteAsync("""
