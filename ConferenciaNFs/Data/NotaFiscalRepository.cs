    private static int CompararNotasConferencia(NotaFiscal a, NotaFiscal b)
    {
        var comparacaoData = DataCompraParser.CompararAscendente(a.DataEmissao, b.DataEmissao);
        if (comparacaoData != 0)
            return comparacaoData;

        var comparacaoFornecedor = string.Compare(a.NomeForn, b.NomeForn, StringComparison.OrdinalIgnoreCase);
        if (comparacaoFornecedor != 0)
            return comparacaoFornecedor;

        return string.Compare(a.NumNota, b.NumNota, StringComparison.OrdinalIgnoreCase);
    }

