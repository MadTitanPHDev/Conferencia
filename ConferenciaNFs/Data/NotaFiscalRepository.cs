    public async Task<int> RecalcularHerancaImportacaoDiaAsync(
        string diaConferencia,
        CancellationToken cancellationToken = default)
    {
        var dia = diaConferencia.Trim();
        if (string.IsNullOrWhiteSpace(dia))
            throw new ArgumentException("Informe o dia da conferencia.", nameof(diaConferencia));

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        if (!ObterHerancaStatusImportacao(connection, transaction: null))
            throw new InvalidOperationException("Ative a heranca de status antes de recalcular.");

        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);

        var notasDia = (await connection.QueryAsync<NotaFiscal>("""
            SELECT *
            FROM NotasFiscais
            WHERE DiaConferencia = @DiaConferencia
            """, new { DiaConferencia = dia }, transaction)).ToList();

        var atualizadas = 0;

        foreach (var nota in notasDia)
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (!OrigemStatusValues.PodeSerAlteradoAutomaticamente(nota.OrigemStatus))
                continue;

            var heranca = ResolverStatusHerdado(
                connection,
                transaction,
                nota.ApelidoLoja,
                nota.NumNota,
                nota.CnpjForn,
                dia,
                nota.NfeChaveAcesso,
                nota.CodCompra);

            if (!heranca.HasValue)
                continue;

            if (StatusHerancaImportacao.TemStatusConferido(nota.StatusConferencia)
                && nota.StatusConferencia != StatusConferenciaValues.Laranja)
                continue;

            if (nota.StatusConferencia == heranca.Value.Status
                && nota.Observacao == heranca.Value.Observacao)
                continue;

            await connection.ExecuteAsync("""
                UPDATE NotasFiscais
                SET StatusConferencia = @StatusConferencia,
                    Observacao = @Observacao,
                    OrigemStatus = @OrigemStatus,
                    StatusHerdadoDeNotaFiscalId = @StatusHerdadoDeNotaFiscalId,
                    StatusAtualizadoPor = @StatusAtualizadoPor
                WHERE Id = @Id
                  AND OrigemStatus <> @OrigemManual
                """, new
            {
                nota.Id,
                StatusConferencia = heranca.Value.Status,
                Observacao = heranca.Value.Observacao,
                OrigemStatus = OrigemStatusValues.Herdado,
                StatusHerdadoDeNotaFiscalId = heranca.Value.FonteNotaFiscalId,
                StatusAtualizadoPor = "Recalculo de heranca",
                OrigemManual = OrigemStatusValues.Manual
            }, transaction);

            atualizadas++;
        }

        ReconciliarFilaDevolucoes(connection, transaction);

        await transaction.CommitAsync(cancellationToken);
        return atualizadas;
    }

    public async Task<int> RecalcularHerancaImportacaoIntervaloAsync(
