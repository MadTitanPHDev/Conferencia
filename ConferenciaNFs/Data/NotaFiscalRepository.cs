    private static void RecalcularHerancaAposRealocacao(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        long notaId,
        bool herancaAtiva)
    {
        var nota = connection.QuerySingleOrDefault<NotaFiscal>("""
            SELECT Id, ApelidoLoja, NumNota, CnpjForn, DiaConferencia,
                   StatusConferencia, Observacao, DataEmissao, CodCompra,
                   COALESCE(NfeChaveAcesso, '') AS NfeChaveAcesso,
                   OrigemStatus
            FROM NotasFiscais
            WHERE Id = @Id
            """, new { Id = notaId }, transaction);

        if (nota is null
            || !herancaAtiva
            || !OrigemStatusValues.PodeSerAlteradoAutomaticamente(nota.OrigemStatus))
            return;

        var heranca = ResolverStatusHerdado(
            connection,
            transaction,
            nota.ApelidoLoja,
            nota.NumNota,
            nota.CnpjForn,
            nota.DiaConferencia,
            nota.NfeChaveAcesso,
            nota.CodCompra);

        if (!heranca.HasValue)
            return;

        if (nota.StatusConferencia == heranca.Value.Status
            && nota.Observacao == heranca.Value.Observacao)
            return;

        connection.Execute("""
            UPDATE NotasFiscais
            SET StatusConferencia = @StatusConferencia,
                Observacao = @Observacao,
                OrigemStatus = @OrigemStatus,
                StatusHerdadoDeNotaFiscalId = @StatusHerdadoDeNotaFiscalId,
                StatusAtualizadoPor = @StatusAtualizadoPor
            WHERE Id = @Id
              AND OrigemStatus <> @OrigemManual
            """, new
        {
            Id = notaId,
            StatusConferencia = heranca.Value.Status,
            Observacao = heranca.Value.Observacao,
            OrigemStatus = OrigemStatusValues.Herdado,
            StatusHerdadoDeNotaFiscalId = heranca.Value.FonteNotaFiscalId,
            StatusAtualizadoPor = "Heranca apos realocacao",
            OrigemManual = OrigemStatusValues.Manual
        }, transaction);
    }

    private static void ReconciliarFilaDevolucoes(
        NpgsqlConnection connection,
        NpgsqlTransaction? transaction)
    {
        connection.Execute("""
            DELETE FROM Devolucoes d
            USING NotasFiscais n
            WHERE d.NotaFiscalId = n.Id
              AND d.StatusDevolucao = @StatusPendente
              AND n.StatusConferencia <> @StatusVermelho
            """, new
        {
            StatusPendente = StatusDevolucaoValues.Pendente,
            StatusVermelho = StatusConferenciaValues.Vermelho
        }, transaction);

        // Varias linhas da mesma NF (um dia de conferencia cada): fica a mais antiga,
        // ou a que ja tem itens da pre-nota.
        connection.Execute($"""
            DELETE FROM Devolucoes d
            USING NotasFiscais n
            WHERE d.NotaFiscalId = n.Id
              AND d.StatusDevolucao = @StatusPendente
              AND EXISTS (
                  SELECT 1
                  FROM Devolucoes d2
                  INNER JOIN NotasFiscais n2 ON n2.Id = d2.NotaFiscalId
                  WHERE d2.Id <> d.Id
                    AND {SqlMesmaIdentidadeNotas}
                    AND (
                        (
                            EXISTS (SELECT 1 FROM DevolucaoItens i WHERE i.DevolucaoId = d2.Id)
                            AND NOT EXISTS (SELECT 1 FROM DevolucaoItens i WHERE i.DevolucaoId = d.Id)
                        )
                        OR (
                            (EXISTS (SELECT 1 FROM DevolucaoItens i WHERE i.DevolucaoId = d2.Id))
                            = (EXISTS (SELECT 1 FROM DevolucaoItens i WHERE i.DevolucaoId = d.Id))
                            AND d2.Id < d.Id
                        )
                    )
              )
            """, new { StatusPendente = StatusDevolucaoValues.Pendente }, transaction);

        connection.Execute($"""
            UPDATE NotasFiscais n
            SET StatusConferencia = @StatusLaranja,
                OrigemStatus = @OrigemSistema,
                StatusHerdadoDeNotaFiscalId = NULL,
                StatusAtualizadoPor = 'Reconciliacao devolucao'
            WHERE n.StatusConferencia = @StatusVermelho
              AND n.OrigemStatus <> @OrigemManual
              AND NOT EXISTS (
                  SELECT 1 FROM Devolucoes d WHERE d.NotaFiscalId = n.Id
              )
              AND EXISTS (
                  SELECT 1
                  FROM Devolucoes d2
                  INNER JOIN NotasFiscais n2 ON n2.Id = d2.NotaFiscalId
                  WHERE n2.Id <> n.Id
                    AND {SqlMesmaIdentidadeNotas}
              )
            """, new
        {
            StatusLaranja = StatusConferenciaValues.Laranja,
            StatusVermelho = StatusConferenciaValues.Vermelho,
            OrigemSistema = OrigemStatusValues.Sistema,
            OrigemManual = OrigemStatusValues.Manual
        }, transaction);
    }

