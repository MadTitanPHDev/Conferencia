            """);

        return resultado.ToList();
    }

    public async Task SalvarLojaOrdemAsync(LojaOrdem loja, CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var numeroEmUso = await connection.ExecuteScalarAsync<int?>("""
            SELECT NumeroOrdem
            FROM LojaOrdem
            WHERE NumeroOrdem = @NumeroOrdem
              AND ApelidoLoja <> @ApelidoLoja
            LIMIT 1
            """, loja);

        if (numeroEmUso.HasValue)
            throw new InvalidOperationException($"O numero {loja.NumeroOrdem} ja esta em uso por outra loja.");

        await connection.ExecuteAsync("""
            INSERT INTO LojaOrdem (ApelidoLoja, NumeroOrdem, NomeExibicao)
            VALUES (@ApelidoLoja, @NumeroOrdem, @NomeExibicao)
            ON CONFLICT (ApelidoLoja) DO UPDATE SET
                NumeroOrdem = EXCLUDED.NumeroOrdem,
                NomeExibicao = EXCLUDED.NomeExibicao;
            """, loja);
    }

    public async Task RemoverLojaOrdemAsync(string apelidoLoja, CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        await connection.ExecuteAsync("""
            DELETE FROM LojaOrdem WHERE ApelidoLoja = @ApelidoLoja
            """, new { ApelidoLoja = apelidoLoja });
    }

    private static async Task<List<NotaFiscal>> LerRegistrosCsvAsync(
        string caminhoArquivo,
        string diaConferencia,
        CancellationToken cancellationToken)
    {
        var delimitador = CsvDelimitadorDetector.Detectar(caminhoArquivo);

        await using var stream = new FileStream(
            caminhoArquivo,
            FileMode.Open,
            FileAccess.Read,
            FileShare.Read,
            bufferSize: 4096,
            useAsync: true);

        using var reader = new StreamReader(stream, Encoding.Latin1, detectEncodingFromByteOrderMarks: true);

        for (var i = 0; i < LinhasMetadados; i++)
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (await reader.ReadLineAsync(cancellationToken) is null)
                throw new InvalidDataException("O arquivo CSV nao possui cabecalho apos as linhas de metadados.");
        }

        var csvConfig = new CsvConfiguration(CultureInfo.InvariantCulture)
        {
            Delimiter = delimitador.ToString(),
            HasHeaderRecord = true,
            MissingFieldFound = null,
            BadDataFound = null,
            HeaderValidated = null,
            TrimOptions = TrimOptions.Trim,
            PrepareHeaderForMatch = args => args.Header.Trim().ToUpperInvariant()
        };

        using var parser = new CsvParser(reader, csvConfig);
        using var csv = new CsvReader(parser);

        var resultado = new List<NotaFiscal>();

        while (await csv.ReadAsync())
        {
            cancellationToken.ThrowIfCancellationRequested();

            var registro = csv.GetRecord<NotaFiscalCsvRecord>();
            if (registro is null)
                continue;

            var numNota = registro.NumNota.Trim();
            var cnpjForn = registro.CnpjForn.Trim();

            if (string.IsNullOrWhiteSpace(numNota) || string.IsNullOrWhiteSpace(cnpjForn))
                continue;

            resultado.Add(new NotaFiscal
            {
                ApelidoLoja = LojaAliasNormalizer.Normalizar(registro.ApelidoLoja),
                NumNota = numNota,
                NomeForn = registro.NomeForn.Trim(),
                CnpjForn = cnpjForn,
                ValorNota = ValorMonetarioParser.Parse(registro.ValorNota),
                DataCompra = registro.DataCompra.Trim(),
                DataEmissao = registro.DataEmissao.Trim(),
                DiaConferencia = diaConferencia,
                ChaveUnica = NotaFiscal.GerarChaveUnica(
                    LojaAliasNormalizer.Normalizar(registro.ApelidoLoja),
                    numNota,
                    cnpjForn,
                    diaConferencia,
                    registro.DataCompra.Trim()),
                StatusConferencia = StatusConferenciaValues.Pendente
            });
        }

        return resultado;
    }

    private NpgsqlConnection CriarConexao() => new(_connectionString);
}
