    private const int LinhasMetadados = 7;

    private readonly string _connectionString;

    public NotaFiscalRepository(string connectionString)
    {
        if (string.IsNullOrWhiteSpace(connectionString))
            throw new InvalidOperationException(
                "ConnectionString do PostgreSQL nao configurada. Edite app-settings.json na pasta do aplicativo.");

        _connectionString = connectionString.Trim();
        InicializarBanco();
    }

    public string ConnectionString => _connectionString;

    public void TestarConexao()
    {
        using var connection = CriarConexao();
        connection.Open();
        connection.ExecuteScalar<int>("SELECT 1");
    }

    private void InicializarBanco()
    {
        using var connection = CriarConexao();
        connection.Open();

        connection.Execute("""
            CREATE TABLE IF NOT EXISTS NotasFiscais (
                Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ApelidoLoja TEXT NOT NULL,
                NumNota TEXT NOT NULL,
                NomeForn TEXT,
                CnpjForn TEXT,
                ValorNota NUMERIC(18,2) NOT NULL DEFAULT 0,
                DataCompra TEXT,
                DataEmissao TEXT NOT NULL DEFAULT '',
                DiaConferencia TEXT NOT NULL DEFAULT '',
                Observacao TEXT NOT NULL DEFAULT '',
                ChaveUnica TEXT NOT NULL UNIQUE,
                StatusConferencia TEXT NOT NULL DEFAULT 'Pendente'
            );

            CREATE INDEX IF NOT EXISTS IX_NotasFiscais_ApelidoLoja
                ON NotasFiscais (ApelidoLoja);

            CREATE INDEX IF NOT EXISTS IX_NotasFiscais_StatusConferencia
                ON NotasFiscais (StatusConferencia);

            CREATE INDEX IF NOT EXISTS IX_NotasFiscais_DataCompra
                ON NotasFiscais (DataCompra);

            CREATE INDEX IF NOT EXISTS IX_NotasFiscais_DiaConferencia
                ON NotasFiscais (DiaConferencia);

            CREATE INDEX IF NOT EXISTS IX_NotasFiscais_NumNota
                ON NotasFiscais (NumNota);
            """);

        NormalizarApelidosExistentes(connection);
        InicializarTabelaLojaOrdem(connection);
    }

    private static void InicializarTabelaLojaOrdem(NpgsqlConnection connection)
    {
        connection.Execute("""
            CREATE TABLE IF NOT EXISTS LojaOrdem (
                ApelidoLoja TEXT PRIMARY KEY,
                NumeroOrdem INTEGER NOT NULL UNIQUE,
                NomeExibicao TEXT NOT NULL
            );

            CREATE INDEX IF NOT EXISTS IX_LojaOrdem_NumeroOrdem
                ON LojaOrdem (NumeroOrdem);
            """);

        AjustarAliasesLojaOrdem(connection);

        foreach (var loja in LojaOrdemSeed.LojasPadrao)
        {
            connection.Execute("""
                INSERT INTO LojaOrdem (ApelidoLoja, NumeroOrdem, NomeExibicao)
                VALUES (@ApelidoLoja, @NumeroOrdem, @NomeExibicao)
                ON CONFLICT (ApelidoLoja) DO NOTHING;
                """, loja);
        }
    }

    private static void NormalizarApelidosExistentes(NpgsqlConnection connection)
    {
        var apelidos = connection.Query<string>("SELECT DISTINCT ApelidoLoja FROM NotasFiscais");
        foreach (var apelidoAtual in apelidos)
        {
            var apelidoNormalizado = LojaAliasNormalizer.Normalizar(apelidoAtual);
            if (apelidoNormalizado == apelidoAtual)
                continue;

            connection.Execute("""
                UPDATE NotasFiscais
                SET ApelidoLoja = @ApelidoNovo
                WHERE ApelidoLoja = @ApelidoAtual
                """, new
            {
                ApelidoAtual = apelidoAtual,
                ApelidoNovo = apelidoNormalizado
            });
        }
    }

    private static void AjustarAliasesLojaOrdem(NpgsqlConnection connection)
    {
        connection.Execute("""
            UPDATE LojaOrdem
            SET ApelidoLoja = 'QUATA FILI', NomeExibicao = 'Quata Filial'
            WHERE ApelidoLoja = 'QUATA FIL';

            UPDATE LojaOrdem
            SET ApelidoLoja = 'MANOEL GOU', NomeExibicao = 'Manoel Goulart'
            WHERE ApelidoLoja = 'MANOEL GO';

            UPDATE LojaOrdem
            SET ApelidoLoja = '__TMP_LUCELIA_CE__'
            WHERE ApelidoLoja = 'LUCELIA CENTRO';

            UPDATE LojaOrdem
            SET ApelidoLoja = 'LUCELIA', NomeExibicao = 'Lucelia'
            WHERE ApelidoLoja = 'LUCELIA CE' AND NumeroOrdem = 20;

            UPDATE LojaOrdem
            SET ApelidoLoja = 'LUCELIA CE', NomeExibicao = 'Lucelia Centro'
            WHERE ApelidoLoja = '__TMP_LUCELIA_CE__';
            """);
    }

    public async Task<int> ImportarCsvAsync(
        string caminhoArquivo,
        string diaConferencia,
        CancellationToken cancellationToken = default)
    {
        if (!File.Exists(caminhoArquivo))
            throw new FileNotFoundException("Arquivo CSV nao encontrado.", caminhoArquivo);

        var dia = diaConferencia.Trim();
        if (string.IsNullOrWhiteSpace(dia))
            throw new ArgumentException("Informe o dia da conferencia para importar o CSV.", nameof(diaConferencia));

        var registros = await LerRegistrosCsvAsync(caminhoArquivo, dia, cancellationToken);
        if (registros.Count == 0)
            return 0;

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);

        var inseridos = 0;

        const string sql = """
            INSERT INTO NotasFiscais (
                ApelidoLoja, NumNota, NomeForn, CnpjForn,
                ValorNota, DataCompra, DataEmissao, DiaConferencia, ChaveUnica, StatusConferencia
            ) VALUES (
                @ApelidoLoja, @NumNota, @NomeForn, @CnpjForn,
                @ValorNota, @DataCompra, @DataEmissao, @DiaConferencia, @ChaveUnica, @StatusConferencia
            )
            ON CONFLICT (ChaveUnica) DO UPDATE SET
                ApelidoLoja = EXCLUDED.ApelidoLoja,
                NomeForn = EXCLUDED.NomeForn,
                ValorNota = EXCLUDED.ValorNota,
                DataCompra = EXCLUDED.DataCompra,
                DiaConferencia = EXCLUDED.DiaConferencia,
                DataEmissao = CASE
                    WHEN EXCLUDED.DataEmissao <> '' THEN EXCLUDED.DataEmissao
                    ELSE NotasFiscais.DataEmissao
                END;
            """;

        const string sqlContarExistente = """
            SELECT 1
            FROM NotasFiscais
            WHERE ChaveUnica = @ChaveUnica
            LIMIT 1
            """;

        foreach (var nota in registros)
        {
            cancellationToken.ThrowIfCancellationRequested();

            var jaExistia = await connection.ExecuteScalarAsync<int?>(
                sqlContarExistente,
                new { nota.ChaveUnica },
                transaction) is not null;

            await connection.ExecuteAsync(sql, nota, transaction);

            if (!jaExistia)
                inseridos++;
        }

        await transaction.CommitAsync(cancellationToken);
        return inseridos;
    }

    public async Task<IReadOnlyList<string>> ObterDatasDisponiveisAsync(
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var datas = await connection.QueryAsync<string>("""
            SELECT DISTINCT DiaConferencia
            FROM NotasFiscais
            WHERE DiaConferencia IS NOT NULL AND TRIM(DiaConferencia) <> ''
            """);

        return datas
            .Where(d => !string.IsNullOrWhiteSpace(d))
            .OrderByDescending(d => d, Comparer<string>.Create(DataCompraParser.Comparar))
            .ToList();
    }

    public async Task<string> ResolverChaveDataCompraAsync(
        DateTime data,
        CancellationToken cancellationToken = default)
    {
        var alvo = data.Date;
        var datas = await ObterDatasDisponiveisAsync(cancellationToken);

        var existente = datas.FirstOrDefault(d =>
            DataCompraParser.TentarConverter(d)?.Date == alvo);

        return existente ?? DataCompraParser.Formatar(alvo);
    }

    public async Task<IReadOnlyList<LojaPendencia>> ObterPendenciasPorLojaAsync(
        string dataCompra,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var resultado = await connection.QueryAsync<LojaPendencia>("""
            SELECT
                n.ApelidoLoja,
                SUM(CASE
                    WHEN n.StatusConferencia IN (@StatusPendente, @StatusAmarelo) THEN 1
                    ELSE 0
                END)::int AS Pendencias,
                COALESCE(MAX(l.NumeroOrdem), 9999) AS NumeroOrdem,
                COALESCE(NULLIF(MAX(l.NomeExibicao), ''), n.ApelidoLoja) AS NomeExibicao
            FROM NotasFiscais n
            LEFT JOIN LojaOrdem l ON l.ApelidoLoja = n.ApelidoLoja
            WHERE n.DiaConferencia = @DiaConferencia
            GROUP BY n.ApelidoLoja
            ORDER BY NumeroOrdem, n.ApelidoLoja
            """, new
        {
            StatusPendente = StatusConferenciaValues.Pendente,
            StatusAmarelo = StatusConferenciaValues.Amarelo,
            DiaConferencia = dataCompra
        });

        return resultado.ToList();
    }

    public async Task<IReadOnlyList<NotaFiscal>> ObterNotasPorLojaAsync(
        string apelidoLoja,
        string dataCompra,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var resultado = await connection.QueryAsync<NotaFiscal>("""
            SELECT *
            FROM NotasFiscais
            WHERE ApelidoLoja = @Loja
              AND DiaConferencia = @DiaConferencia
            """, new { Loja = apelidoLoja, DiaConferencia = dataCompra });

        return resultado
            .OrderBy(n => n, Comparer<NotaFiscal>.Create(CompararNotasConferencia))
            .ToList();
    }

    private static int CompararNotasConferencia(NotaFiscal a, NotaFiscal b)
    {
        var comparacaoData = DataCompraParser.CompararAscendente(a.DataEmissao, b.DataEmissao);
        if (comparacaoData != 0)
            return comparacaoData;

        var comparacaoFornecedor = string.Compare(a.NomeForn, b.NomeForn, StringComparison.OrdinalIgnoreCase);
        if (comparacaoFornecedor != 0)
            return comparacaoFornecedor;

        return string.Compare(a.NumNota, b.NumNota, StringComparison.OrdinalIgnoreCase);
    }

    public async Task<IReadOnlyList<NotaPesquisaResultado>> PesquisarPrimeiraConferenciaPorNumNotaAsync(
        string numNota,
        CancellationToken cancellationToken = default)
    {
        var termo = numNota.Trim();
        if (string.IsNullOrWhiteSpace(termo))
            return [];

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var notas = (await connection.QueryAsync<NotaFiscal>("""
            SELECT *
            FROM NotasFiscais
            WHERE LOWER(TRIM(NumNota)) = LOWER(TRIM(@Termo))
            """, new { Termo = termo })).ToList();

        return notas
            .GroupBy(n => $"{n.NumNota}|{n.CnpjForn}", StringComparer.OrdinalIgnoreCase)
            .Select(grupo =>
            {
                var ordenadas = grupo
                    .OrderBy(n => n, Comparer<NotaFiscal>.Create((a, b) =>
                        DataCompraParser.CompararAscendente(a.DiaConferencia, b.DiaConferencia)))
                    .ToList();

                var primeira = ordenadas[0];
                return new NotaPesquisaResultado
                {
                    NumNota = primeira.NumNota,
                    ApelidoLoja = primeira.ApelidoLoja,
                    NomeForn = primeira.NomeForn,
                    DataPrimeiraConferencia = primeira.DiaConferencia,
                    StatusConferencia = primeira.StatusConferencia,
                    Observacao = primeira.Observacao,
                    OcorrenciasTotais = ordenadas.Count
                };
            })
            .OrderBy(r => r.NomeForn, StringComparer.OrdinalIgnoreCase)
            .ThenBy(r => r.ApelidoLoja, StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    public async Task<IReadOnlyList<NotaFiscal>> ObterTodasNotasPorDataAsync(
        string dataCompra,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var notas = (await connection.QueryAsync<NotaFiscal>("""
            SELECT *
            FROM NotasFiscais
            WHERE DiaConferencia = @DiaConferencia
            """, new { DiaConferencia = dataCompra })).ToList();

        var ordens = await connection.QueryAsync<(string ApelidoLoja, int NumeroOrdem)>("""
            SELECT ApelidoLoja, NumeroOrdem
            FROM LojaOrdem
            """);

        var ordemPorLoja = ordens.ToDictionary(o => o.ApelidoLoja, o => o.NumeroOrdem, StringComparer.Ordinal);

        return notas
            .OrderBy(n => ordemPorLoja.TryGetValue(n.ApelidoLoja, out var ordem) ? ordem : 9999)
            .ThenBy(n => n, Comparer<NotaFiscal>.Create(CompararNotasConferencia))
            .ToList();
    }

    public async Task AtualizarStatusConferenciaAsync(
        long id,
        string status,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

