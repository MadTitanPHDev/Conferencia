    public async Task AtualizarDistribuidoraAsync(
        string cnpjForn,
        int? prazoDevolucaoDias,
        bool rastrearPrazo,
        CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(cnpjForn))
            throw new ArgumentException("CNPJ da distribuidora e obrigatorio.", nameof(cnpjForn));

        if (prazoDevolucaoDias is < 0)
            throw new ArgumentOutOfRangeException(nameof(prazoDevolucaoDias), "Prazo nao pode ser negativo.");

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var linhas =         await connection.ExecuteAsync("""
            UPDATE Distribuidoras
            SET PrazoDevolucaoDias = @PrazoDevolucaoDias,
                RastrearPrazo = @RastrearPrazo
            WHERE regexp_replace(COALESCE(CnpjForn, ''), '[^0-9]', '', 'g') = @CnpjForn
            """, new
        {
            CnpjForn = CnpjNormalizer.Normalizar(cnpjForn),
            PrazoDevolucaoDias = prazoDevolucaoDias,
            RastrearPrazo = rastrearPrazo
        });

        if (linhas == 0)
            throw new InvalidOperationException($"Distribuidora com CNPJ {cnpjForn} nao encontrada.");
    }

    public async Task<IReadOnlyList<string>> ObterDatasDisponiveisAsync(
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var datas = await connection.QueryAsync<string>("""
            SELECT DISTINCT DiaConferencia
            FROM NotasFiscais
            WHERE DiaConferencia IS NOT NULL AND TRIM(DiaConferencia) <> ''
            """);

        return datas
            .Where(d => !string.IsNullOrWhiteSpace(d))
            .OrderByDescending(d => d, Comparer<string>.Create(DataCompraParser.Comparar))
            .ToList();
    }

    public async Task<string> ResolverChaveDataCompraAsync(
        DateTime data,
        CancellationToken cancellationToken = default)
    {
        var alvo = data.Date;
        var datas = await ObterDatasDisponiveisAsync(cancellationToken);

        var existente = datas.FirstOrDefault(d =>
            DataCompraParser.TentarConverter(d)?.Date == alvo);

        return existente ?? DataCompraParser.Formatar(alvo);
    }

    public async Task<IReadOnlyList<LojaPendencia>> ObterPendenciasPorLojaAsync(
        string dataCompra,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var resultado = await connection.QueryAsync<LojaPendencia>("""
            SELECT
                n.ApelidoLoja,
                SUM(CASE
                    WHEN n.StatusConferencia IN (@StatusPendente, @StatusAmarelo) THEN 1
                    ELSE 0
                END)::int AS Pendencias,
                COALESCE(MAX(l.NumeroOrdem), 9999) AS NumeroOrdem,
                COALESCE(NULLIF(MAX(l.NomeExibicao), ''), n.ApelidoLoja) AS NomeExibicao
            FROM NotasFiscais n
            LEFT JOIN LojaOrdem l ON l.ApelidoLoja = n.ApelidoLoja
            WHERE n.DiaConferencia = @DiaConferencia
            GROUP BY n.ApelidoLoja
            ORDER BY NumeroOrdem, n.ApelidoLoja
            """, new
        {
            StatusPendente = StatusConferenciaValues.Pendente,
            StatusAmarelo = StatusConferenciaValues.Amarelo,
            DiaConferencia = dataCompra
        });

        return resultado.ToList();
    }

    public async Task<IReadOnlyList<NotaFiscal>> ObterNotasPorLojaAsync(
        string apelidoLoja,
        string dataCompra,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var resultado = await connection.QueryAsync<NotaFiscal>("""
            SELECT *
            FROM NotasFiscais
            WHERE ApelidoLoja = @Loja
              AND DiaConferencia = @DiaConferencia
            """, new { Loja = apelidoLoja, DiaConferencia = dataCompra });

        return resultado
            .OrderBy(n => n, Comparer<NotaFiscal>.Create(CompararNotasConferencia))
            .ToList();
    }

    private static int CompararNotasConferencia(NotaFiscal a, NotaFiscal b)
    {
        var comparacaoData = DataCompraParser.CompararAscendente(a.DataEmissao, b.DataEmissao);
        if (comparacaoData != 0)
            return comparacaoData;

        var comparacaoFornecedor = string.Compare(a.NomeForn, b.NomeForn, StringComparison.OrdinalIgnoreCase);
        if (comparacaoFornecedor != 0)
            return comparacaoFornecedor;

        return string.Compare(a.NumNota, b.NumNota, StringComparison.OrdinalIgnoreCase);
    }

    public async Task<IReadOnlyList<NotaPesquisaResultado>> PesquisarPrimeiraConferenciaPorNumNotaAsync(
        string numNota,
        CancellationToken cancellationToken = default)
    {
        var termo = numNota.Trim();
        if (string.IsNullOrWhiteSpace(termo))
            return [];

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var notas = (await connection.QueryAsync<NotaFiscal>("""
            SELECT *
            FROM NotasFiscais
            WHERE LOWER(TRIM(NumNota)) = LOWER(TRIM(@Termo))
            """, new { Termo = termo })).ToList();

        return notas
            .GroupBy(n => $"{n.NumNota}|{n.CnpjForn}", StringComparer.OrdinalIgnoreCase)
            .Select(grupo =>
            {
                var ordenadas = grupo
                    .OrderBy(n => n, Comparer<NotaFiscal>.Create((a, b) =>
                        DataCompraParser.CompararAscendente(a.DiaConferencia, b.DiaConferencia)))
                    .ToList();

                var primeira = ordenadas[0];
                return new NotaPesquisaResultado
                {
                    NumNota = primeira.NumNota,
                    ApelidoLoja = primeira.ApelidoLoja,
                    NomeForn = primeira.NomeForn,
                    DataPrimeiraConferencia = primeira.DiaConferencia,
                    StatusConferencia = primeira.StatusConferencia,
                    Observacao = primeira.Observacao,
                    OcorrenciasTotais = ordenadas.Count
                };
            })
            .OrderBy(r => r.NomeForn, StringComparer.OrdinalIgnoreCase)
            .ThenBy(r => r.ApelidoLoja, StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    public async Task<IReadOnlyList<NotaFiscal>> ObterTodasNotasPorDataAsync(
        string dataCompra,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var notas = (await connection.QueryAsync<NotaFiscal>("""
            SELECT *
            FROM NotasFiscais
            WHERE DiaConferencia = @DiaConferencia
            """, new { DiaConferencia = dataCompra })).ToList();

        var ordens = await connection.QueryAsync<(string ApelidoLoja, int NumeroOrdem)>("""
            SELECT ApelidoLoja, NumeroOrdem
            FROM LojaOrdem
            """);

        var ordemPorLoja = ordens.ToDictionary(o => o.ApelidoLoja, o => o.NumeroOrdem, StringComparer.Ordinal);

        return notas
            .OrderBy(n => ordemPorLoja.TryGetValue(n.ApelidoLoja, out var ordem) ? ordem : 9999)
            .ThenBy(n => n, Comparer<NotaFiscal>.Create(CompararNotasConferencia))
            .ToList();
    }

    public async Task AtualizarStatusConferenciaAsync(
        long id,
        string status,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);

        var statusAtual = await connection.QuerySingleOrDefaultAsync<string>("""
            SELECT StatusConferencia
            FROM NotasFiscais
            WHERE Id = @Id
            """, new { Id = id }, transaction);

        if (statusAtual is null)
            throw new InvalidOperationException($"Nota com Id {id} nao encontrada.");

        await connection.ExecuteAsync("""
            UPDATE NotasFiscais
            SET StatusConferencia = @Status
            WHERE Id = @Id
            """, new { Id = id, Status = status }, transaction);

        if (status == StatusConferenciaValues.Vermelho
            && statusAtual != StatusConferenciaValues.Vermelho)
        {
            var dataMinima = await ObterDataMinimaDevolucoesInternalAsync(connection, transaction);
            if (await NotaEntraNoPeriodoDevolucaoAsync(connection, transaction, id, dataMinima))
                await RegistrarDevolucaoPendenteAsync(connection, transaction, id, cancellationToken);
        }
        else if (status != StatusConferenciaValues.Vermelho
                 && statusAtual == StatusConferenciaValues.Vermelho)
        {
            // So remove pendencias da fila; devolucoes concluidas permanecem no historico.
            await connection.ExecuteAsync("""
                DELETE FROM Devolucoes
                WHERE NotaFiscalId = @NotaFiscalId
                  AND StatusDevolucao = @StatusPendente
                """, new
            {
                NotaFiscalId = id,
                StatusPendente = StatusDevolucaoValues.Pendente
            }, transaction);
        }

        await transaction.CommitAsync(cancellationToken);
    }

    private static async Task<bool> NotaEntraNoPeriodoDevolucaoAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        long notaFiscalId,
        DateTime? dataMinima)
    {
        if (!dataMinima.HasValue)
            return true;

        var dataEmissao = await connection.QuerySingleOrDefaultAsync<string?>("""
            SELECT DataEmissao
            FROM NotasFiscais
            WHERE Id = @Id
            """, new { Id = notaFiscalId }, transaction);

        var emissao = DataCompraParser.TentarConverter(dataEmissao);
        if (!emissao.HasValue)
            return false;

        return emissao.Value.Date >= dataMinima.Value.Date;
    }

    private static bool DevolucaoVisivelNoPeriodo(DevolucaoItem item, DateTime? dataMinima)
    {
        if (item.StatusDevolucao != StatusDevolucaoValues.Pendente)
            return true;

        if (!dataMinima.HasValue)
            return true;

        var emissao = item.DataReferenciaRastreio;
        return emissao.HasValue && emissao.Value.Date >= dataMinima.Value.Date;
    }

    private static async Task RegistrarDevolucaoPendenteAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        long notaFiscalId,
        CancellationToken cancellationToken)
    {
        var dataMarcada = DataCompraParser.Formatar(DateTime.Today);
        await connection.ExecuteAsync("""
            INSERT INTO Devolucoes (NotaFiscalId, StatusDevolucao, DataMarcada, DataConclusao, Observacao)
            VALUES (@NotaFiscalId, @StatusDevolucao, @DataMarcada, NULL, '')
            ON CONFLICT (NotaFiscalId) DO UPDATE SET
                StatusDevolucao = EXCLUDED.StatusDevolucao,
                DataMarcada = EXCLUDED.DataMarcada,
                DataConclusao = NULL,
                Observacao = ''
            WHERE Devolucoes.StatusDevolucao = @StatusPendente;
            """, new
        {
            NotaFiscalId = notaFiscalId,
            StatusDevolucao = StatusDevolucaoValues.Pendente,
            StatusPendente = StatusDevolucaoValues.Pendente,
            DataMarcada = dataMarcada
        }, transaction);
    }

    public async Task<IReadOnlyList<DevolucaoItem>> ObterDevolucoesAsync(
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var resultado = await connection.QueryAsync<DevolucaoItem>($"""
            SELECT
                d.Id,
                d.NotaFiscalId,
                n.ApelidoLoja,
                n.NumNota,
                n.NomeForn,
                n.CnpjForn,
                n.ValorNota,
                n.DataEmissao,
                n.DiaConferencia,
                d.StatusDevolucao,
                d.DataMarcada,
                d.DataConclusao,
                d.Observacao,
                dist.PrazoDevolucaoDias,
                COALESCE(dist.RastrearPrazo, FALSE) AS RastrearPrazo
            FROM Devolucoes d
            INNER JOIN NotasFiscais n ON n.Id = d.NotaFiscalId
            {SqlJoinDistribuidoraPorCnpj}
            ORDER BY
                CASE d.StatusDevolucao
                    WHEN 'Pendente' THEN 0
                    WHEN 'Devolvida' THEN 1
                    ELSE 2
                END,
                n.DataEmissao,
                n.NomeForn,
                n.NumNota
            """);

        var dataMinima = await ObterDataMinimaDevolucoesInternalAsync(connection, transaction: null);
        var lista = resultado.ToList();
        if (!dataMinima.HasValue)
            return lista;

        return lista
            .Where(d => DevolucaoVisivelNoPeriodo(d, dataMinima))
            .ToList();
    }

    public async Task<DateTime?> ObterDataMinimaDevolucoesAsync(
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        return await ObterDataMinimaDevolucoesInternalAsync(connection, transaction: null);
    }

    public async Task SalvarDataMinimaDevolucoesAsync(
        DateTime? dataMinima,
        bool removerPendentesAnteriores,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);

        var valor = dataMinima.HasValue
            ? DataCompraParser.Formatar(dataMinima.Value.Date)
            : string.Empty;

        await connection.ExecuteAsync("""
            INSERT INTO AppConfig (Chave, Valor)
            VALUES (@Chave, @Valor)
            ON CONFLICT (Chave) DO UPDATE SET Valor = EXCLUDED.Valor;
            """, new
        {
            Chave = ConfigDevolucoesDataMinima,
            Valor = valor
        }, transaction);

        if (removerPendentesAnteriores && dataMinima.HasValue)
        {
            var pendentes = (await connection.QueryAsync<DevolucaoItem>($"""
                SELECT
                    d.Id,
                    d.NotaFiscalId,
                    n.ApelidoLoja,
                    n.NumNota,
                    n.NomeForn,
                    n.CnpjForn,
                    n.ValorNota,
                    n.DataEmissao,
                    n.DiaConferencia,
                    d.StatusDevolucao,
                    d.DataMarcada,
                    d.DataConclusao,
                    d.Observacao,
                    dist.PrazoDevolucaoDias,
                    COALESCE(dist.RastrearPrazo, FALSE) AS RastrearPrazo
                FROM Devolucoes d
                INNER JOIN NotasFiscais n ON n.Id = d.NotaFiscalId
                {SqlJoinDistribuidoraPorCnpj}
                WHERE d.StatusDevolucao = @StatusPendente
                """, new { StatusPendente = StatusDevolucaoValues.Pendente }, transaction)).ToList();

            var idsRemover = pendentes
                .Where(d => !DevolucaoVisivelNoPeriodo(d, dataMinima))
                .Select(d => d.Id)
                .ToList();

            if (idsRemover.Count > 0)
            {
                await connection.ExecuteAsync("""
                    DELETE FROM Devolucoes
                    WHERE Id = ANY(@Ids)
                    """, new { Ids = idsRemover.ToArray() }, transaction);
            }
        }

        await transaction.CommitAsync(cancellationToken);
    }

    private static async Task<DateTime?> ObterDataMinimaDevolucoesInternalAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction? transaction)
    {
        var valor = await connection.QuerySingleOrDefaultAsync<string>("""
            SELECT Valor
            FROM AppConfig
            WHERE Chave = @Chave
            """, new { Chave = ConfigDevolucoesDataMinima }, transaction);

        return DataCompraParser.TentarConverter(valor);
    }

    public async Task AtualizarStatusDevolucaoAsync(
        long devolucaoId,
        string statusDevolucao,
        string? observacao,
        CancellationToken cancellationToken = default)
    {
        if (statusDevolucao is not (
            StatusDevolucaoValues.Pendente
            or StatusDevolucaoValues.Devolvida
            or StatusDevolucaoValues.PerdeuPrazo))
        {
            throw new ArgumentException("Status de devolucao invalido.", nameof(statusDevolucao));
        }

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var dataConclusaoNova = statusDevolucao == StatusDevolucaoValues.Pendente
            ? null
            : DataCompraParser.Formatar(DateTime.Today);

        var linhas = await connection.ExecuteAsync("""
            UPDATE Devolucoes
            SET StatusDevolucao = @StatusDevolucao,
                Observacao = @Observacao,
                DataConclusao = CASE
                    WHEN @StatusDevolucao = 'Pendente' THEN NULL
                    WHEN StatusDevolucao <> @StatusDevolucao THEN @DataConclusaoNova
                    WHEN DataConclusao IS NULL OR TRIM(DataConclusao) = '' THEN @DataConclusaoNova
                    ELSE DataConclusao
                END
            WHERE Id = @Id
            """, new
        {
            Id = devolucaoId,
            StatusDevolucao = statusDevolucao,
            Observacao = observacao?.Trim() ?? string.Empty,
            DataConclusaoNova = dataConclusaoNova
        });

        if (linhas == 0)
            throw new InvalidOperationException($"Devolucao com Id {devolucaoId} nao encontrada.");
    }

