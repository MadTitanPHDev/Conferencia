    public async Task SalvarDataMinimaDevolucoesAsync(
        DateTime? dataMinima,
        bool removerPendentesAnteriores,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);

        var valor = dataMinima.HasValue
            ? DataCompraParser.Formatar(dataMinima.Value.Date)
            : string.Empty;

        await connection.ExecuteAsync("""
            INSERT INTO AppConfig (Chave, Valor)
            VALUES (@Chave, @Valor)
            ON CONFLICT (Chave) DO UPDATE SET Valor = EXCLUDED.Valor;
            """, new
        {
            Chave = ConfigDevolucoesDataMinima,
            Valor = valor
        }, transaction);

        if (removerPendentesAnteriores && dataMinima.HasValue)
            RemoverDevolucoesForaDoPeriodo(connection, transaction, dataMinima.Value.Date);

        await transaction.CommitAsync(cancellationToken);
    }

    private static async Task<DateTime?> ObterDataMinimaDevolucoesInternalAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction? transaction)
    {
        var valor = await connection.QuerySingleOrDefaultAsync<string>("""
            SELECT Valor
            FROM AppConfig
            WHERE Chave = @Chave
            """, new { Chave = ConfigDevolucoesDataMinima }, transaction);

        return DataCompraParser.TentarConverter(valor);
    }

    public async Task AtualizarStatusDevolucaoAsync(
        long devolucaoId,
        string statusDevolucao,
        CancellationToken cancellationToken = default)
    {
        if (statusDevolucao is not (
            StatusDevolucaoValues.Pendente
            or StatusDevolucaoValues.Devolvida
            or StatusDevolucaoValues.Absorvido
            or StatusDevolucaoValues.PerdeuPrazo))
        {
            throw new ArgumentException("Status de devolucao invalido.", nameof(statusDevolucao));
        }

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var dataConclusaoNova = statusDevolucao == StatusDevolucaoValues.Pendente
            ? null
            : DataCompraParser.Formatar(DateTime.Today);

        var linhas = await connection.ExecuteAsync("""
            UPDATE Devolucoes
            SET StatusDevolucao = @StatusDevolucao,
                DataConclusao = CASE
                    WHEN @StatusDevolucao = 'Pendente' THEN NULL
                    WHEN StatusDevolucao <> @StatusDevolucao THEN @DataConclusaoNova
                    WHEN DataConclusao IS NULL OR TRIM(DataConclusao) = '' THEN @DataConclusaoNova
                    ELSE DataConclusao
                END
            WHERE Id = @Id
            """, new
        {
            Id = devolucaoId,
            StatusDevolucao = statusDevolucao,
            DataConclusaoNova = dataConclusaoNova
        });

        if (linhas == 0)
            throw new InvalidOperationException($"Devolucao com Id {devolucaoId} nao encontrada.");
    }

