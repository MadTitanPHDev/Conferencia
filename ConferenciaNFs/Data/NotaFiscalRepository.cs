    public async Task<int> ImportarCsvAsync(
        string caminhoArquivo,
        string diaConferencia,
        CancellationToken cancellationToken = default)
    {
        if (!File.Exists(caminhoArquivo))
            throw new FileNotFoundException("Arquivo CSV nao encontrado.", caminhoArquivo);

        var dia = diaConferencia.Trim();
        if (string.IsNullOrWhiteSpace(dia))
            throw new ArgumentException("Informe o dia da conferencia para importar o CSV.", nameof(diaConferencia));

        var registros = await LerRegistrosCsvAsync(caminhoArquivo, dia, cancellationToken);
        if (registros.Count == 0)
            return 0;

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);

        var inseridos = 0;
        var herancaAtiva = ObterHerancaStatusImportacao(connection, transaction);

        const string sql = """
            INSERT INTO NotasFiscais (
                ApelidoLoja, NumNota, NomeForn, CnpjForn,
                ValorNota, DataCompra, DataEmissao, DiaConferencia, ChaveUnica,
                StatusConferencia, Observacao, OrigemStatus,
                StatusHerdadoDeNotaFiscalId, StatusAtualizadoPor
            ) VALUES (
                @ApelidoLoja, @NumNota, @NomeForn, @CnpjForn,
                @ValorNota, @DataCompra, @DataEmissao, @DiaConferencia, @ChaveUnica,
                @StatusConferencia, @Observacao, @OrigemStatus,
                @StatusHerdadoDeNotaFiscalId, @StatusAtualizadoPor
            )
            ON CONFLICT (ChaveUnica) DO UPDATE SET
                ApelidoLoja = EXCLUDED.ApelidoLoja,
                NomeForn = CASE
                    WHEN EXCLUDED.NomeForn <> ''
                     AND EXCLUDED.NomeForn !~ '^[0-9./ -]+$'
                     AND regexp_replace(EXCLUDED.NomeForn, '[^0-9]', '', 'g')
                       <> regexp_replace(COALESCE(EXCLUDED.CnpjForn, ''), '[^0-9]', '', 'g')
                    THEN EXCLUDED.NomeForn
                    ELSE NotasFiscais.NomeForn
                END,
                ValorNota = EXCLUDED.ValorNota,
                DataCompra = EXCLUDED.DataCompra,
                DiaConferencia = EXCLUDED.DiaConferencia,
                DataEmissao = CASE
                    WHEN EXCLUDED.DataEmissao <> '' THEN EXCLUDED.DataEmissao
                    ELSE NotasFiscais.DataEmissao
                END;
            """;

        const string sqlContarExistente = """
            SELECT 1
            FROM NotasFiscais
            WHERE ChaveUnica = @ChaveUnica
            LIMIT 1
            """;

        foreach (var nota in registros)
        {
            cancellationToken.ThrowIfCancellationRequested();

            var jaExistia = await connection.ExecuteScalarAsync<int?>(
                sqlContarExistente,
                new { nota.ChaveUnica },
                transaction) is not null;

            if (herancaAtiva && !jaExistia)
            {
                var heranca = ResolverStatusHerdado(
                    connection,
                    transaction,
                    nota.ApelidoLoja,
                    nota.NumNota,
                    nota.CnpjForn,
                    dia,
                    nota.NfeChaveAcesso);

                if (heranca.HasValue)
                {
                    nota.StatusConferencia = heranca.Value.Status;
                    nota.Observacao = heranca.Value.Observacao;
                    nota.OrigemStatus = OrigemStatusValues.Herdado;
                    nota.StatusHerdadoDeNotaFiscalId = heranca.Value.FonteNotaFiscalId;
                    nota.StatusAtualizadoPor = "Importacao CSV";
                }
            }

            await connection.ExecuteAsync(sql, nota, transaction);

            if (!jaExistia)
                inseridos++;
        }

        await SincronizarDistribuidorasAsync(connection, registros, transaction, cancellationToken);

        ReconciliarFilaDevolucoes(connection, transaction);

        await transaction.CommitAsync(cancellationToken);
        return inseridos;
    }

    public async Task<VsmSyncResult> SincronizarComprasVsmAsync(
        IReadOnlyList<CompraVsm> compras,
        string diaConferencia,
        CancellationToken cancellationToken = default)
    {
        var dia = diaConferencia.Trim();
        if (string.IsNullOrWhiteSpace(dia))
            throw new ArgumentException("Informe o dia da conferencia.", nameof(diaConferencia));

        var resultado = new VsmSyncResult { Lidas = compras.Count };
        if (compras.Count == 0)
            return resultado;

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var mapaLojas = (await connection.QueryAsync<LojaVsmMap>("""
            SELECT CodLoja, ApelidoLoja, NomeExibicao, CnpjLoja
            FROM LojaVsmMap
            """)).ToDictionary(l => l.CodLoja);

        var nomesPorCnpj = await CarregarNomesFornecedorPorCnpjAsync(connection, cancellationToken);
        var herancaAtiva = ObterHerancaStatusImportacao(connection, transaction: null);

        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);

        const string sql = """
            INSERT INTO NotasFiscais (
                ApelidoLoja, NumNota, NomeForn, CnpjForn,
                ValorNota, DataCompra, DataEmissao, DiaConferencia, ChaveUnica,
                StatusConferencia, Observacao, CodCompra, NfeChaveAcesso,
                OrigemStatus, StatusHerdadoDeNotaFiscalId, StatusAtualizadoPor
            ) VALUES (
                @ApelidoLoja, @NumNota, @NomeForn, @CnpjForn,
                @ValorNota, @DataCompra, @DataEmissao, @DiaConferencia, @ChaveUnica,
                @StatusConferencia, @Observacao, @CodCompra, @NfeChaveAcesso,
                @OrigemStatus, @StatusHerdadoDeNotaFiscalId, @StatusAtualizadoPor
            )
            ON CONFLICT (ChaveUnica) DO UPDATE SET
                ApelidoLoja = EXCLUDED.ApelidoLoja,
                NomeForn = CASE
                    WHEN EXCLUDED.NomeForn <> ''
                     AND EXCLUDED.NomeForn !~ '^[0-9./ -]+$'
                     AND regexp_replace(EXCLUDED.NomeForn, '[^0-9]', '', 'g')
                       <> regexp_replace(COALESCE(EXCLUDED.CnpjForn, ''), '[^0-9]', '', 'g')
                    THEN EXCLUDED.NomeForn
                    ELSE NotasFiscais.NomeForn
                END,
                ValorNota = EXCLUDED.ValorNota,
                DataCompra = EXCLUDED.DataCompra,
                DiaConferencia = EXCLUDED.DiaConferencia,
                CodCompra = EXCLUDED.CodCompra,
                NfeChaveAcesso = EXCLUDED.NfeChaveAcesso,
                DataEmissao = CASE
                    WHEN EXCLUDED.DataEmissao <> '' THEN EXCLUDED.DataEmissao
                    ELSE NotasFiscais.DataEmissao
                END;
            """;

        const string sqlContarExistente = """
            SELECT 1
            FROM NotasFiscais
            WHERE ChaveUnica = @ChaveUnica
            LIMIT 1
            """;

        var notasLidas = new List<NotaFiscal>();
        foreach (var compra in compras)
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (!mapaLojas.TryGetValue(compra.CodLoja, out var loja))
            {
                resultado.Ignoradas++;
                continue;
            }

            var numNota = compra.NumNota?.Trim() ?? string.Empty;
            var cnpjForn = CnpjNormalizer.Normalizar(compra.CnpjForn);
            if (string.IsNullOrWhiteSpace(numNota) || string.IsNullOrWhiteSpace(cnpjForn))
            {
                resultado.Ignoradas++;
                continue;
            }

            var dataCompra = compra.DataCompra.HasValue
                ? DataCompraParser.Formatar(compra.DataCompra.Value)
                : dia;
            var dataEmissao = compra.DataEmissao.HasValue
                ? DataCompraParser.Formatar(compra.DataEmissao.Value)
                : string.Empty;

            nomesPorCnpj.TryGetValue(cnpjForn, out var nomeMapa);
            var nomeForn = NomeFornecedorEscolha.Escolher(
                [compra.NomeForn, nomeMapa],
                cnpjForn);

            var nota = new NotaFiscal
            {
                ApelidoLoja = loja.ApelidoLoja,
                NumNota = numNota,
                NomeForn = nomeForn,
                CnpjForn = cnpjForn,
                ValorNota = compra.ValorNota,
                DataCompra = dataCompra,
                DataEmissao = dataEmissao,
                DiaConferencia = dia,
                ChaveUnica = NotaFiscal.GerarChaveUnica(loja.ApelidoLoja, numNota, cnpjForn, dia, dataCompra),
                StatusConferencia = StatusConferenciaValues.Pendente,
                Observacao = string.Empty,
                CodCompra = compra.CodCompra,
                NfeChaveAcesso = compra.NfeChaveAcesso?.Trim() ?? string.Empty,
                OrigemStatus = OrigemStatusValues.Sistema,
                StatusAtualizadoPor = "Sincronizacao VSM"
            };
            notasLidas.Add(nota);

            var relocacao = (Relocou: false, IdRecalcular: (long?)null);
            if (compra.CodCompra > 0)
            {
                relocacao = RelocarNotaVsmPorCodCompra(
                    connection,
                    transaction,
                    compra.CodCompra,
                    nota);
            }

            if (relocacao.Relocou)
            {
                resultado.Relocadas++;
                if (relocacao.IdRecalcular.HasValue)
                {
                    RecalcularHerancaAposRealocacao(
                        connection,
                        transaction,
                        relocacao.IdRecalcular.Value,
                        herancaAtiva);
                }
            }

            var jaExistia = await connection.ExecuteScalarAsync<int?>(
                sqlContarExistente,
                new { nota.ChaveUnica },
                transaction) is not null;

            if (herancaAtiva && !relocacao.Relocou)
            {
                var heranca = ResolverStatusHerdado(
                    connection,
                    transaction,
                    nota.ApelidoLoja,
                    nota.NumNota,
                    nota.CnpjForn,
                    dia,
                    nota.NfeChaveAcesso,
                    nota.CodCompra);

                if (heranca.HasValue)
                {
                    nota.StatusConferencia = heranca.Value.Status;
                    nota.Observacao = heranca.Value.Observacao;
                    nota.OrigemStatus = OrigemStatusValues.Herdado;
                    nota.StatusHerdadoDeNotaFiscalId = heranca.Value.FonteNotaFiscalId;
                }
            }

            await connection.ExecuteAsync(sql, nota, transaction);

            if (herancaAtiva
                && jaExistia
                && !relocacao.Relocou
                && nota.StatusConferencia != StatusConferenciaValues.Pendente)
            {
                await connection.ExecuteAsync("""
                    UPDATE NotasFiscais
                    SET StatusConferencia = @StatusConferencia,
                        Observacao = @Observacao,
                        OrigemStatus = @OrigemStatus,
                        StatusHerdadoDeNotaFiscalId = @StatusHerdadoDeNotaFiscalId,
                        StatusAtualizadoPor = @StatusAtualizadoPor
                    WHERE ChaveUnica = @ChaveUnica
                      AND StatusConferencia = @StatusPendente
                      AND OrigemStatus <> @OrigemManual
                    """, new
                {
                    nota.ChaveUnica,
                    nota.StatusConferencia,
                    nota.Observacao,
                    nota.OrigemStatus,
                    nota.StatusHerdadoDeNotaFiscalId,
                    nota.StatusAtualizadoPor,
                    OrigemManual = OrigemStatusValues.Manual,
                    StatusPendente = StatusConferenciaValues.Pendente
                }, transaction);
            }

            if (jaExistia)
                resultado.Atualizadas++;
            else
                resultado.Inseridas++;
        }

        await SincronizarDistribuidorasAsync(connection, notasLidas, transaction, cancellationToken);

        await transaction.CommitAsync(cancellationToken);
        return resultado;
    }

    private static (bool Relocou, long? IdRecalcular) RelocarNotaVsmPorCodCompra(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        int codCompra,
        NotaFiscal destino)
    {
        if (codCompra <= 0)
            return (false, null);

        var deslocadas = connection.Query<NotaVsmDeslocada>("""
            SELECT Id, ApelidoLoja, NumNota, CnpjForn, DiaConferencia, DataCompra,
                   CodCompra, COALESCE(NfeChaveAcesso, '') AS NfeChaveAcesso
            FROM NotasFiscais
            WHERE CodCompra = @CodCompra
              AND ChaveUnica <> @ChaveUnica
              AND DiaConferencia = @DiaConferencia
            """, new
        {
            CodCompra = codCompra,
            destino.ChaveUnica,
            DiaConferencia = destino.DiaConferencia
        }, transaction).ToList();

        // Registros de outros dias sao historico e permanecem intactos.
        // A realocacao corrige apenas loja/chave da mesma compra dentro do mesmo dia.
        var doMesmoDia = deslocadas
            .Where(d => RelocacaoNotaVsm.MesmoDiaConferencia(
                d.DiaConferencia,
                destino.DiaConferencia))
            .ToList();

        if (doMesmoDia.Count == 0)
            return (false, null);

        long? idRecalcular = null;

        foreach (var deslocada in doMesmoDia)
        {
            var id = RelocarOuMesclarNotaVsm(
                connection,
                transaction,
                deslocada.Id,
                destino.ApelidoLoja,
                destino.ChaveUnica,
                destino.CodCompra,
                destino.NfeChaveAcesso);

            if (id.HasValue)
                idRecalcular = id;
        }

        return (true, idRecalcular);
    }

    private static string[] NormalizarDiasConferencia(IReadOnlyList<string> dias)
    {
        if (dias is null || dias.Count == 0)
            throw new ArgumentException("Informe ao menos um dia de conferencia.", nameof(dias));

        var limpos = dias
            .Select(d => d?.Trim() ?? string.Empty)
            .Where(d => d.Length > 0)
            .Distinct(StringComparer.Ordinal)
            .ToArray();

        if (limpos.Length == 0)
            throw new ArgumentException("Informe ao menos um dia de conferencia.", nameof(dias));

        return limpos;
    }

    private static async Task<Dictionary<string, string>> CarregarNomesFornecedorPorCnpjAsync(
        NpgsqlConnection connection,
        CancellationToken cancellationToken)
    {
        var nomes = new Dictionary<string, string>(StringComparer.Ordinal);

        var daDistribuidora = await connection.QueryAsync<(string Cnpj, string? Nome)>(new CommandDefinition("""
            SELECT Cnpj, Nome
            FROM (
                SELECT DISTINCT ON (regexp_replace(COALESCE(CnpjForn, ''), '[^0-9]', '', 'g'))
                    regexp_replace(COALESCE(CnpjForn, ''), '[^0-9]', '', 'g') AS Cnpj,
                    TRIM(NomeForn) AS Nome
                FROM Distribuidoras
                WHERE TRIM(COALESCE(CnpjForn, '')) <> ''
                ORDER BY
                    regexp_replace(COALESCE(CnpjForn, ''), '[^0-9]', '', 'g'),
                    CASE
                        WHEN TRIM(COALESCE(NomeForn, '')) ~ '^[0-9./ -]+$' THEN 1
                        WHEN regexp_replace(TRIM(COALESCE(NomeForn, '')), '[^0-9]', '', 'g')
                           = regexp_replace(COALESCE(CnpjForn, ''), '[^0-9]', '', 'g') THEN 1
                        ELSE 0
                    END,
                    length(TRIM(COALESCE(NomeForn, ''))) DESC
            ) s
            """, cancellationToken: cancellationToken));

        foreach (var item in daDistribuidora)
        {
            if (string.IsNullOrWhiteSpace(item.Cnpj) || string.IsNullOrWhiteSpace(item.Nome))
                continue;
            if (NomeFornecedorEscolha.EhRotuloCnpj(item.Nome, item.Cnpj))
                continue;
            nomes[item.Cnpj] = item.Nome;
        }

        var dasNotas = await connection.QueryAsync<(string Cnpj, string? Nome)>(new CommandDefinition("""
            SELECT Cnpj, Nome
            FROM (
                SELECT DISTINCT ON (regexp_replace(COALESCE(CnpjForn, ''), '[^0-9]', '', 'g'))
                    regexp_replace(COALESCE(CnpjForn, ''), '[^0-9]', '', 'g') AS Cnpj,
                    TRIM(NomeForn) AS Nome
                FROM NotasFiscais
                WHERE TRIM(COALESCE(CnpjForn, '')) <> ''
                ORDER BY
                    regexp_replace(COALESCE(CnpjForn, ''), '[^0-9]', '', 'g'),
                    CASE
                        WHEN TRIM(COALESCE(NomeForn, '')) ~ '^[0-9./ -]+$' THEN 1
                        WHEN regexp_replace(TRIM(COALESCE(NomeForn, '')), '[^0-9]', '', 'g')
                           = regexp_replace(COALESCE(CnpjForn, ''), '[^0-9]', '', 'g') THEN 1
                        ELSE 0
                    END,
                    length(TRIM(COALESCE(NomeForn, ''))) DESC,
                    Id DESC
            ) s
            """, cancellationToken: cancellationToken));

        foreach (var item in dasNotas)
        {
            if (string.IsNullOrWhiteSpace(item.Cnpj) || string.IsNullOrWhiteSpace(item.Nome))
                continue;
            if (NomeFornecedorEscolha.EhRotuloCnpj(item.Nome, item.Cnpj))
                continue;
            if (!nomes.ContainsKey(item.Cnpj))
                nomes[item.Cnpj] = item.Nome;
        }

        return nomes;
    }

