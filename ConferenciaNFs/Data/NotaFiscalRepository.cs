    private static void NormalizarApelidosExistentes(NpgsqlConnection connection)
    {
        var apelidos = connection.Query<string>("SELECT DISTINCT ApelidoLoja FROM NotasFiscais");
        foreach (var apelidoAtual in apelidos)
        {
            var apelidoNormalizado = LojaAliasNormalizer.Normalizar(apelidoAtual);
            if (apelidoNormalizado == apelidoAtual)
                continue;

            connection.Execute("""
                UPDATE NotasFiscais
                SET ApelidoLoja = @ApelidoNovo
                WHERE ApelidoLoja = @ApelidoAtual
                """, new
            {
                ApelidoAtual = apelidoAtual,
                ApelidoNovo = apelidoNormalizado
            });
        }
    }

