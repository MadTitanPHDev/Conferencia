                NotaFiscalId BIGINT NULL REFERENCES NotasFiscais(Id) ON DELETE SET NULL,
                ApelidoLoja TEXT NOT NULL DEFAULT '',
                NumNota TEXT NOT NULL DEFAULT '',
                DiaConferencia TEXT NOT NULL DEFAULT '',
                StatusAnterior TEXT NOT NULL DEFAULT '',
                StatusNovo TEXT NOT NULL DEFAULT '',
                ObservacaoAnterior TEXT NOT NULL DEFAULT '',
                ObservacaoNova TEXT NOT NULL DEFAULT '',
                OrigemStatus TEXT NOT NULL DEFAULT 'Sistema',
                StatusHerdadoDeNotaFiscalId BIGINT NULL,
                AtualizadoPor TEXT NOT NULL DEFAULT '',
                CriadoEm TIMESTAMPTZ NOT NULL DEFAULT NOW()
            );

            CREATE INDEX IF NOT EXISTS IX_NotaStatusHistorico_NotaFiscalId
                ON NotaStatusHistorico (NotaFiscalId);
            CREATE INDEX IF NOT EXISTS IX_NotaStatusHistorico_CriadoEm
                ON NotaStatusHistorico (CriadoEm);
            """);

        var migracaoAplicada = connection.ExecuteScalar<string?>("""
            SELECT Valor FROM AppConfig WHERE Chave = @Chave
            """, new { Chave = ConfigMigracaoOrigemStatus });

        if (!string.Equals(migracaoAplicada, "1", StringComparison.Ordinal))
        {
            using var transaction = connection.BeginTransaction();
            connection.Execute("""
                UPDATE NotasFiscais
                SET OrigemStatus = CASE
                        WHEN StatusConferencia = @Pendente THEN @Sistema
                        ELSE @Manual
                    END,
                    StatusAtualizadoEm = NOW(),
                    StatusAtualizadoPor = 'Migracao 1.0.27'
                """, new
            {
                Pendente = StatusConferenciaValues.Pendente,
                Sistema = OrigemStatusValues.Sistema,
                Manual = OrigemStatusValues.Manual
            }, transaction);

            connection.Execute("""
                INSERT INTO AppConfig (Chave, Valor)
                VALUES (@Chave, '1')
                ON CONFLICT (Chave) DO UPDATE SET Valor = EXCLUDED.Valor
                """, new { Chave = ConfigMigracaoOrigemStatus }, transaction);
            transaction.Commit();
        }

        connection.Execute("""
            CREATE OR REPLACE FUNCTION registrar_historico_status_nota()
            RETURNS TRIGGER AS $func$
            BEGIN
                IF OLD.StatusConferencia IS DISTINCT FROM NEW.StatusConferencia
                   OR OLD.Observacao IS DISTINCT FROM NEW.Observacao
                   OR OLD.OrigemStatus IS DISTINCT FROM NEW.OrigemStatus
                   OR OLD.StatusHerdadoDeNotaFiscalId IS DISTINCT FROM NEW.StatusHerdadoDeNotaFiscalId
                THEN
                    NEW.StatusAtualizadoEm := NOW();
                    INSERT INTO NotaStatusHistorico (
                        NotaFiscalId, ApelidoLoja, NumNota, DiaConferencia,
                        StatusAnterior, StatusNovo, ObservacaoAnterior, ObservacaoNova,
                        OrigemStatus, StatusHerdadoDeNotaFiscalId, AtualizadoPor, CriadoEm)
                    VALUES (
                        NEW.Id, NEW.ApelidoLoja, NEW.NumNota, NEW.DiaConferencia,
                        OLD.StatusConferencia, NEW.StatusConferencia,
                        OLD.Observacao, NEW.Observacao,
                        NEW.OrigemStatus, NEW.StatusHerdadoDeNotaFiscalId,
                        NEW.StatusAtualizadoPor, NOW());
                END IF;
                RETURN NEW;
            END;
            $func$ LANGUAGE plpgsql;

            DROP TRIGGER IF EXISTS TR_NotaStatusHistorico ON NotasFiscais;
            CREATE TRIGGER TR_NotaStatusHistorico
            BEFORE UPDATE ON NotasFiscais
            FOR EACH ROW EXECUTE PROCEDURE registrar_historico_status_nota();
            """);
    }

