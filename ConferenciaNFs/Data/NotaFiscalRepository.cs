    private void InicializarBanco()
    {
        using var connection = CriarConexao();
        connection.Open();

        connection.Execute("""
            CREATE TABLE IF NOT EXISTS NotasFiscais (
                Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ApelidoLoja TEXT NOT NULL,
                NumNota TEXT NOT NULL,
                NomeForn TEXT,
                CnpjForn TEXT,
                ValorNota NUMERIC(18,2) NOT NULL DEFAULT 0,
                DataCompra TEXT,
                DataEmissao TEXT NOT NULL DEFAULT '',
                DiaConferencia TEXT NOT NULL DEFAULT '',
                Observacao TEXT NOT NULL DEFAULT '',
                ChaveUnica TEXT NOT NULL UNIQUE,
                StatusConferencia TEXT NOT NULL DEFAULT 'Pendente'
            );

            CREATE INDEX IF NOT EXISTS IX_NotasFiscais_ApelidoLoja
                ON NotasFiscais (ApelidoLoja);

            CREATE INDEX IF NOT EXISTS IX_NotasFiscais_StatusConferencia
                ON NotasFiscais (StatusConferencia);

            CREATE INDEX IF NOT EXISTS IX_NotasFiscais_DataCompra
                ON NotasFiscais (DataCompra);

            CREATE INDEX IF NOT EXISTS IX_NotasFiscais_DiaConferencia
                ON NotasFiscais (DiaConferencia);

            CREATE INDEX IF NOT EXISTS IX_NotasFiscais_NumNota
                ON NotasFiscais (NumNota);
            """);

        NormalizarApelidosExistentes(connection);
        InicializarTabelaLojaOrdem(connection);
        InicializarTabelaDistribuidoras(connection);
        InicializarTabelaAppConfig(connection);
        InicializarTabelaDevolucoes(connection);
    }

