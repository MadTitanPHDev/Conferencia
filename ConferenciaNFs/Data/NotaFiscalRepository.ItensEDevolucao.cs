    public async Task AdicionarObservacaoDevolucaoAsync(
        long devolucaoId,
        string texto,
        CancellationToken cancellationToken = default)
    {
        var recado = (texto ?? string.Empty).Trim();
        if (recado.Length == 0)
            throw new ArgumentException("Informe um recado para salvar.", nameof(texto));

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var tx = await connection.BeginTransactionAsync(cancellationToken);

        var ultima = await connection.QuerySingleOrDefaultAsync<string>("""
            SELECT Texto
            FROM DevolucaoObservacoes
            WHERE DevolucaoId = @DevolucaoId
            ORDER BY Id DESC
            LIMIT 1
            """, new { DevolucaoId = devolucaoId }, tx);

        if (string.Equals(ultima?.Trim(), recado, StringComparison.Ordinal))
        {
            await tx.CommitAsync(cancellationToken);
            return;
        }

        await connection.ExecuteAsync("""
            INSERT INTO DevolucaoObservacoes (DevolucaoId, Texto, CriadaEm)
            VALUES (@DevolucaoId, @Texto, @CriadaEm)
            """,
            new
            {
                DevolucaoId = devolucaoId,
                Texto = recado,
                CriadaEm = DevolucaoObservacaoHistorico.FormatarData(DateTime.Now)
            },
            tx);

        var historico = (await connection.QueryAsync<DevolucaoObservacao>("""
            SELECT Id, DevolucaoId, Texto, CriadaEm
            FROM DevolucaoObservacoes
            WHERE DevolucaoId = @DevolucaoId
            ORDER BY Id
            """, new { DevolucaoId = devolucaoId }, tx)).AsList();

        await connection.ExecuteAsync("""
            UPDATE Devolucoes
            SET Observacao = @Observacao
            WHERE Id = @Id
            """,
            new
            {
                Id = devolucaoId,
                Observacao = DevolucaoObservacaoHistorico.Juntar(historico)
            },
            tx);

        await tx.CommitAsync(cancellationToken);
    }
