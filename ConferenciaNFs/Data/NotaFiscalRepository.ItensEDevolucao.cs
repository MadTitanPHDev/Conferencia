    private static void InicializarTabelaItensNota(NpgsqlConnection connection)
    {
        connection.Execute("""
            CREATE TABLE IF NOT EXISTS ItensNota (
                Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                NotaFiscalId BIGINT NOT NULL REFERENCES NotasFiscais(Id) ON DELETE CASCADE,
                CodCompra INTEGER NULL,
                Sequencia INTEGER NOT NULL,
                CodProd INTEGER NOT NULL DEFAULT 0,
                NomeProd TEXT NOT NULL DEFAULT '',
                BarrasEan TEXT NOT NULL DEFAULT '',
                BarrasEanTrib TEXT NOT NULL DEFAULT '',
                QuantItemCompra NUMERIC(18,4) NOT NULL DEFAULT 0,
                ValorItemCompra NUMERIC(18,4) NOT NULL DEFAULT 0,
                Desconto NUMERIC(18,4) NOT NULL DEFAULT 0,
                CustoNota NUMERIC(18,4) NOT NULL DEFAULT 0,
                NumLote TEXT NULL,
                DataValidade TEXT NULL,
                AtualizadoEm TEXT NOT NULL DEFAULT '',
                UNIQUE (NotaFiscalId, Sequencia)
            );

            CREATE INDEX IF NOT EXISTS IX_ItensNota_NotaFiscalId
                ON ItensNota (NotaFiscalId);
            """);
    }

