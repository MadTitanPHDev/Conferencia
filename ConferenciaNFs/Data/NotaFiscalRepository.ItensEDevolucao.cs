    }

    public async Task SalvarMotivoDevolucaoAsync(
        string descricao,
        CancellationToken cancellationToken = default)
    {
        var texto = (descricao ?? string.Empty).Trim();
        if (texto.Length < 3)
            throw new InvalidOperationException("Informe um motivo com pelo menos 3 caracteres.");

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var existente = await connection.QuerySingleOrDefaultAsync<MotivoDevolucao>(new CommandDefinition(
            "SELECT Id, Descricao, Ativo FROM MotivosDevolucao WHERE Descricao = @Descricao",
            new { Descricao = texto },
            cancellationToken: cancellationToken));

        if (existente is not null)
        {
            if (existente.Ativo)
                throw new InvalidOperationException("Este motivo ja esta cadastrado.");

            await connection.ExecuteAsync(new CommandDefinition(
                "UPDATE MotivosDevolucao SET Ativo = TRUE WHERE Id = @Id",
                new { existente.Id },
                cancellationToken: cancellationToken));
            return;
        }

        await connection.ExecuteAsync(new CommandDefinition(
            "INSERT INTO MotivosDevolucao (Descricao, Ativo) VALUES (@Descricao, TRUE)",
            new { Descricao = texto },
            cancellationToken: cancellationToken));
    }

