    public async Task<IReadOnlyDictionary<long, IReadOnlyList<DevolucaoItemPreNota>>> ObterItensPreNotaPorDevolucoesAsync(
        IReadOnlyList<long> devolucaoIds,
        CancellationToken cancellationToken = default)
    {
        if (devolucaoIds.Count == 0)
            return new Dictionary<long, IReadOnlyList<DevolucaoItemPreNota>>();

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);

        var linhas = await connection.QueryAsync<DevolucaoItemLinhaBanco>(new CommandDefinition(
            """
            SELECT
                DevolucaoId, Sequencia, CodProd, NomeProd, BarrasEan,
                Quantidade, CustoNota, Motivo, Classe
            FROM DevolucaoItens
            WHERE DevolucaoId = ANY(@Ids)
            ORDER BY DevolucaoId, Sequencia
            """,
            new { Ids = devolucaoIds.ToArray() },
            cancellationToken: cancellationToken));

        return linhas
            .GroupBy(l => l.DevolucaoId)
            .ToDictionary(
                g => g.Key,
                g => (IReadOnlyList<DevolucaoItemPreNota>)g.Select(l => new DevolucaoItemPreNota
                {
                    Sequencia = l.Sequencia,
                    CodProd = l.CodProd,
                    NomeProd = l.NomeProd,
                    BarrasEan = l.BarrasEan,
                    Quantidade = l.Quantidade,
                    CustoNota = l.CustoNota,
                    Motivo = l.Motivo,
                    Classe = l.Classe
                }).ToList());
    }

