    private static void InicializarTabelaDevolucaoObservacoes(NpgsqlConnection connection)
    {
        connection.Execute("""
            CREATE TABLE IF NOT EXISTS DevolucaoObservacoes (
                Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                DevolucaoId BIGINT NOT NULL REFERENCES Devolucoes(Id) ON DELETE CASCADE,
                Texto TEXT NOT NULL,
                CriadaEm TEXT NOT NULL
            );

            CREATE INDEX IF NOT EXISTS IX_DevolucaoObservacoes_DevolucaoId
                ON DevolucaoObservacoes (DevolucaoId);
            """);

        connection.Execute("""
            INSERT INTO DevolucaoObservacoes (DevolucaoId, Texto, CriadaEm)
            SELECT
                d.Id,
                TRIM(d.Observacao),
                COALESCE(NULLIF(TRIM(d.DataMarcada), ''), to_char(CURRENT_TIMESTAMP, 'DD/MM/YYYY HH24:MI'))
            FROM Devolucoes d
            WHERE TRIM(COALESCE(d.Observacao, '')) <> ''
              AND NOT EXISTS (
                    SELECT 1
                    FROM DevolucaoObservacoes o
                    WHERE o.DevolucaoId = d.Id
              );
            """);
    }

    public async Task SubstituirItensNotaAsync(
        long notaFiscalId,
        IReadOnlyList<ItemNotaSnapshot> itens,
        CancellationToken cancellationToken = default)
    {
        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var tx = await connection.BeginTransactionAsync(cancellationToken);

        await connection.ExecuteAsync(new CommandDefinition(
            "DELETE FROM ItensNota WHERE NotaFiscalId = @NotaFiscalId",
            new { NotaFiscalId = notaFiscalId },
            tx,
            cancellationToken: cancellationToken));

        var agora = DateTime.Now.ToString("dd/MM/yyyy HH:mm", CultureInfo.GetCultureInfo("pt-BR"));
        foreach (var item in itens)
        {
            await connection.ExecuteAsync(new CommandDefinition(
                """
                INSERT INTO ItensNota (
                    NotaFiscalId, CodCompra, Sequencia, CodProd, NomeProd,
                    BarrasEan, BarrasEanTrib, QuantItemCompra, ValorItemCompra,
                    Desconto, CustoNota, NumLote, DataValidade, AtualizadoEm)
                VALUES (
                    @NotaFiscalId, @CodCompra, @Sequencia, @CodProd, @NomeProd,
                    @BarrasEan, @BarrasEanTrib, @QuantItemCompra, @ValorItemCompra,
                    @Desconto, @CustoNota, @NumLote, @DataValidade, @AtualizadoEm)
                """,
                new
                {
                    item.NotaFiscalId,
                    item.CodCompra,
                    item.Sequencia,
                    item.CodProd,
                    item.NomeProd,
                    item.BarrasEan,
                    item.BarrasEanTrib,
                    item.QuantItemCompra,
                    item.ValorItemCompra,
                    item.Desconto,
                    item.CustoNota,
                    item.NumLote,
                    item.DataValidade,
                    AtualizadoEm = agora
                },
                tx,
                cancellationToken: cancellationToken));
        }

        await tx.CommitAsync(cancellationToken);
    }

