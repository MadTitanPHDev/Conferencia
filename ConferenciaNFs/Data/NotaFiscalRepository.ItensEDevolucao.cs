    public async Task ConfirmarPreNotaAsync(
        long notaFiscalId,
        IReadOnlyList<DevolucaoItemPreNota> itens,
        CancellationToken cancellationToken = default)
    {
        if (itens.Count == 0)
            throw new InvalidOperationException("Selecione ao menos um produto para devolver.");

        await using var connection = CriarConexao();
        await connection.OpenAsync(cancellationToken);
        await using var tx = await connection.BeginTransactionAsync(cancellationToken);

        var statusAtual = await connection.QuerySingleOrDefaultAsync<string>("""
            SELECT StatusConferencia
            FROM NotasFiscais
            WHERE Id = @Id
            """, new { Id = notaFiscalId }, tx);

        if (statusAtual is null)
            throw new InvalidOperationException($"Nota com Id {notaFiscalId} nao encontrada.");

        var devolucaoId = await RegistrarDevolucaoPendenteAsync(connection, tx, notaFiscalId, cancellationToken);

        if (devolucaoId == 0)
        {
            await connection.ExecuteAsync("""
                UPDATE NotasFiscais
                SET StatusConferencia = @Status
                WHERE Id = @Id
                """, new { Id = notaFiscalId, Status = StatusConferenciaValues.Vermelho }, tx);
            await tx.CommitAsync(cancellationToken);
            return;
        }

        var notaDonaId = await connection.QuerySingleAsync<long>(
            "SELECT NotaFiscalId FROM Devolucoes WHERE Id = @Id",
            new { Id = devolucaoId },
            tx);

        await connection.ExecuteAsync("""
            UPDATE NotasFiscais
            SET StatusConferencia = @Status
            WHERE Id = @Id
            """, new
        {
            Id = notaFiscalId,
            Status = notaDonaId == notaFiscalId
                ? StatusConferenciaValues.Vermelho
                : StatusConferenciaValues.Laranja
        }, tx);

        await connection.ExecuteAsync(
            "DELETE FROM DevolucaoItens WHERE DevolucaoId = @DevolucaoId",
            new { DevolucaoId = devolucaoId },
            tx);

        foreach (var item in itens)
        {
            await connection.ExecuteAsync("""
                INSERT INTO DevolucaoItens (
                    DevolucaoId, NotaFiscalId, Sequencia, CodProd, NomeProd,
                    BarrasEan, Quantidade, CustoNota, Motivo, Classe)
                VALUES (
                    @DevolucaoId, @NotaFiscalId, @Sequencia, @CodProd, @NomeProd,
                    @BarrasEan, @Quantidade, @CustoNota, @Motivo, @Classe)
                """,
                new
                {
                    DevolucaoId = devolucaoId,
                    NotaFiscalId = notaFiscalId,
                    item.Sequencia,
                    item.CodProd,
                    item.NomeProd,
                    item.BarrasEan,
                    item.Quantidade,
                    item.CustoNota,
                    item.Motivo,
                    item.Classe
                },
                tx);
        }

        await connection.ExecuteAsync("""
            UPDATE Devolucoes
            SET Andamento = @Andamento
            WHERE Id = @Id
              AND StatusDevolucao = @StatusPendente
            """,
            new
            {
                Id = devolucaoId,
                Andamento = AndamentoDevolucaoValues.AguardandoLoja,
                StatusPendente = StatusDevolucaoValues.Pendente
            },
            tx);

        await tx.CommitAsync(cancellationToken);
    }

